# -*- coding: utf-8 -*-
"""
暗物质：框架最大空白的定量诊断（2026-09-17）
================================================
原文（批05 §2.3 / §3）主张：
  暗物质 = 普朗克尺度诸元对涨落的**空间投影**残余（ε × 空间活跃度 f_space）
  暗能量 = 同一涨落的**时间投影**残余
  两者同源；另有第三候选机制「镜像支引力投影」（批1），三者未统一

DM-1  用 ε_eff = 1/N（全息稀释）算 ρ_DM：差多少？需要 f_space 多少？
DM-2  镜像支朴素预测的**硬检验**：50:50 ⟹ Ω_dm 应 = Ω_b
DM-3  空间/时间投影比 Ω_cdm/Ω_Λ
DM-4  登记：Ω_cdm 与 π/12 的接近（很可能是巧合）
"""
import math

c = 299792458.0
G = 6.67430e-11
hbar = 1.054571817e-34
lP = math.sqrt(hbar * G / c ** 3)
Mpc = 3.0856775814913673e22
H0 = 67.66 * 1e3 / Mpc

mP = math.sqrt(hbar * c / G)
rhoP = mP / lP ** 3                      # kg/m³
rho_crit = 3 * H0 ** 2 / (8 * math.pi * G)
RH = c / H0
N = (RH / lP) ** 2
eps_eff = 1.0 / N

OM_b, OM_cdm, OM_L, OM_m = 0.0493, 0.2618, 0.6889, 0.3111


def line(t):
    print("\n" + "=" * 74)
    print(t)
    print("=" * 74)


def chk(name, got, want, tol=1e-9):
    ok = abs(got - want) <= tol * max(1.0, abs(want))
    print("  [%s] %-46s got=%.10g  want=%.10g" % ("OK" if ok else "XX", name, got, want))
    return ok


# ---------------------------------------------------------------- DM-1
line("DM-1  ε_eff = 1/N 路线：ρ_DM 差多少？f_space 要取多少？")
rho_DM_frame = eps_eff * rhoP
rho_DM_obs = OM_cdm * rho_crit
print("  ρ_P = %.6g kg/m³ ；N = %.6g ；ε_eff = 1/N = %.6g" % (rhoP, N, eps_eff))
print("  ρ_DM(框架, f_space=1) = ε_eff·ρ_P = %.6g kg/m³" % rho_DM_frame)
print("  ρ_DM(观测)            = %.6g kg/m³" % rho_DM_obs)
ratio = rho_DM_frame / rho_DM_obs
print("  ⟹ 超出 %.3f 倍 ；需 **f_space = %.6f = 1/%.1f**" % (ratio, 1 / ratio, ratio))
print("  （原文自己在批05 §3.3 记『差 ~4 倍』—— 那是它用了不同的 ρ_raw/ε 取值；")
print("    用全息稀释 ε=1/N 时是 32 倍，两者别混。）")
print()
print("  等价写法：ρ_DM = ρ_P/(32N) ⟹ Ω_cdm = [H²/(32G)]/[3H²/(8πG)] = 8π/96 = **π/12**")

# ---------------------------------------------------------------- DM-2
line("DM-2  镜像支朴素预测的**硬检验**（可真判）")
print("  A2 方向性：反份入镜像支 B−、正份留本支 B+；50:50 ⟹ ρ_B− = ρ_B+")
print("  若暗物质 = B− 的引力投影，且 B− 只含与重子对应的反份 ⟹ **Ω_dm 应 = Ω_b**")
print("    Ω_b    = %.4f" % OM_b)
print("    Ω_cdm  = %.4f  （观测）" % OM_cdm)
print("  ⟹ **差 %.2f 倍** —— 朴素的镜像支暗物质模型被观测否证" % (OM_cdm / OM_b))
print()
print("  反向看：若 B− 是 B+ 的完整镜像（含全部组分），则 Ω_dm 应 ≈ Ω_total = 1，")
print("     比观测大 %.2f 倍 —— **同样否证**。" % (1.0 / OM_cdm))
print("  ⟹ 镜像支模型需要额外的『稀释/屏蔽』机制才能落在 0.26 上，目前没有。")

# ---------------------------------------------------------------- DM-3
line("DM-3  空间投影 / 时间投影 之比")
r = OM_cdm / OM_L
print("  Ω_cdm / Ω_Λ = %.6f / %.6f = **%.6f**" % (OM_cdm, OM_L, r))
for name, v in (("3/8", 3 / 8), ("π/8", math.pi / 8), ("1/φ²", 1 / 1.618033988749895 ** 2),
                ("1/e", 1 / math.e), ("ln2", math.log(2)), ("Ω_m", OM_m)):
    print("    %-8s = %.6f   偏差 %+.2f%%" % (name, v, 100 * (v - r) / r))
print("  ⚠️ 3/8 差 1.3%%、1/φ² 差 0.5%% —— 都是数值占卜，**无机制，勿采信**。")

# ---------------------------------------------------------------- DM-4
line("DM-4  登记：Ω_cdm 与 π/12")
v = math.pi / 12
print("  π/12      = %.8f" % v)
print("  Ω_cdm(观测) = %.8f" % OM_cdm)
print("  ⟹ 差 %.4f%%" % (100 * abs(v - OM_cdm) / OM_cdm))
print("  ⚠️ 但**必须看误差棒**——Ω_cdm 的实测值随参数组浮动：")
for name, och2, hh in (("Planck18 TT,TE,EE+lowE", 0.12011, 0.6736),
                       ("Planck18 +lensing", 0.12011, 0.6766),
                       ("Planck18 +BAO", 0.11933, 0.6766)):
    val = och2 / hh ** 2
    print("    %-24s Ω_c h²=%.5f h=%.4f ⟹ Ω_c = %.5f   对 π/12 偏差 %+.2f%%"
          % (name, och2, hh, val, 100 * (v - val) / val))
print("  ⟹ 偏差实测 **−1.10% ~ +0.43%**（不是脚本里那个 0.0002%，")
print("     那个是因为 Ω_cdm=0.2618 系由 Ω_m−Ω_b 倒推得到的四位舍入值，恰与 π/12 撞上）。")
print("  ⟹ 仍然偏近，但**精度不足以采信**；需要的是 **1/32 = f_space 的机制**，")
print("     有机制后 Ω_cdm = π/12 才是预言。")

line("结论")
print("""  ❌ **暗物质仍是框架最大空白，而且本轮把它量化了**：
     · ε_eff = 1/N 路线给 ρ_DM 大 **32 倍** ⟹ 需要 f_space = 1/32（无机制）
     · **镜像支朴素模型被否证**：50:50 ⟹ Ω_dm = Ω_b = 0.049，观测 0.262，差 **5.31 倍**
       （若 B− 是完整镜像则差 3.82 倍，同样否证）
     · 空间/时间投影比 Ω_cdm/Ω_Λ = 0.380，凑得上 3/8、1/φ²，但**无机制**

  ⟹ 框架目前对暗物质**没有任何定量预言**，三个候选机制都过不了数量级检验。
  ⟹ 最该补的是：**f_space（空间活跃度）的第一性定义**，这是批05 机制 B 的核心缺口。
""")
