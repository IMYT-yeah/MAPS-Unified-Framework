def sub(p, old, new, tag):
    s = io.open(p, encoding="utf-8").read()
    n = s.count(old)
    if n != 1:
        BAD.append("{} 命中 {}".format(tag, n))
        return False
    io.open(p, "w", encoding="utf-8").write(s.replace(old, new, 1))
    OK.append(tag)
    return True


