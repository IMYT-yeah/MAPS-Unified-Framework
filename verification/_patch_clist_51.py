import io
import os
import re

P = os.path.join(os.path.dirname(os.path.abspath(__file__)), "工程期望清单.md")
OK = [0]
FAIL = [0]


def sub_once(old, new, tag):
    t = io.open(P, encoding="utf-8").read()
    n = t.count(old)
    if n != 1:
        FAIL[0] += 1
        print("  [XX] {:<30} 命中 {} 次 —— 拒绝".format(tag, n))
        return False
    io.open(P, "w", encoding="utf-8").write(t.replace(old, new, 1))
    OK[0] += 1
    print("  [OK] {:<30} 已改".format(tag))
    return True


# ---------------------------------------------------------------- 1. 顺延
L = io.open(P, encoding="utf-8").read().split("\n")
idx = [i for i, s in enumerate(L) if s.startswith("### 1.")]
print("=== 1. 小节顺延（降序，按内容定位）===")
for i in sorted(idx, reverse=True):
    m = re.match(r"### 1\.(\d+)\s+(.*)", L[i])
    num = int(m.group(1))
    rest = m.group(2)
    new = "### 1.{} {}".format(num + 1, rest)
    print("  [OK] 行 {:>4}：{:<24} → {}".format(i + 1, L[i][:24], new))
    L[i] = new
    OK[0] += 1
io.open(P, "w", encoding="utf-8").write("\n".join(L))

# ---------------------------------------------------------------- 2. 新小节
