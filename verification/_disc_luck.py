print("\n[LK-5] ★ 那要证明「**你**的参与跟坏结果相关」，需要多少样本？")
def n_per_group(p1, p2, alpha=0.05, power=0.80):
    """两比例检验的每组样本量（正态近似）"""
    z_a = 1.959963985          # alpha = 0.05 双侧
    z_b = 0.841621234          # power = 0.80
    pbar = (p1 + p2) / 2.0
    d = abs(p1 - p2)
    return 2.0 * (z_a + z_b) ** 2 * pbar * (1 - pbar) / d ** 2

CASES = [
    ("强效应：坏结果率 0.70 vs 0.50", 0.70, 0.50),
    ("中等：0.60 vs 0.50",             0.60, 0.50),
    ("弱效应：0.55 vs 0.50",           0.55, 0.50),
]
print("      {:<32} {:>14} {:>14}".format("要检测的效应", "每组需 n", "两组合计"))
for name, p1, p2 in CASES:
    n = n_per_group(p1, p2)
    print("      {:<32} {:>14.0f} {:>14.0f}".format(name, math.ceil(n), math.ceil(n) * 2))
print("      ⚠️ 假设：一年有 20–50 次「你能记住的参与决策」⟹ 要凑够**每组 ~390 次**")
