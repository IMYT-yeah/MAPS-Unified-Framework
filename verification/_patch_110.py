def rd(p):
    return io.open(p, encoding="utf-8").read()


def wr(p, t):
    io.open(p, "w", encoding="utf-8").write(t)


def sub_once(path, old, new, tag):
    t = rd(path)
    n = t.count(old)
    if n != 1:
        print("  [XX] " + tag + " 命中 " + str(n) + " 次 —— 拒绝")
        BAD.append(tag)
        return
    wr(path, t.replace(old, new, 1))
    print("  [OK] " + tag + " 已改")


def insert_after_line(path, contains, block, tag, before=False):
    """在「含 contains 的那一行」之后（或之前）插入 block（多行字符串）"""
    lines = rd(path).split("\n")
    idx = [i for i, s in enumerate(lines) if contains in s]
    if len(idx) != 1:
        print("  [XX] " + tag + " 行锚点命中 " + str(len(idx)) + " 次 —— 拒绝")
        BAD.append(tag)
        return
    i = idx[0]
    pos = i if before else i + 1
    lines[pos:pos] = block.split("\n")
    wr(path, "\n".join(lines))
    print("  [OK] " + tag + " 已插入（行 " + str(pos + 1) + "）")


