print("\n[顺延小节]")
txt = io.open(P, encoding="utf-8").read()
lines = txt.split("\n")
pat = re.compile(r"^### 1\.(\d+) (第 \d+ 轮)")
idxs = []
for i, s in enumerate(lines):
    m = pat.match(s)
    if m:
        idxs.append((i, int(m.group(1))))
print("  参与顺延的小节：{}".format([n for _, n in idxs]))
for i, n in sorted(idxs, key=lambda x: -x[1]):
    lines[i] = lines[i].replace("### 1.{} ".format(n), "### 1.{} ".format(n + 1), 1)
io.open(P, "w", encoding="utf-8").write("\n".join(lines))
nums = sorted(n for _, n in idxs)
print("  改后编号：{}-{}".format(nums[0] + 1, nums[-1] + 1))

