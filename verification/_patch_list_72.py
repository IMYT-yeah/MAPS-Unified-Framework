OK, BAD = [], []


def sub_once(old, new, tag):
    t = io.open(P, encoding="utf-8").read()
    n = t.count(old)
    if n != 1:
        print("  [XX] {:<34} 命中 {} 次 —— 拒绝".format(tag, n))
        BAD.append(tag)
        return
    io.open(P, "w", encoding="utf-8").write(t.replace(old, new, 1))
    print("  [OK] {:<34} 已改".format(tag))
    OK.append(tag)


