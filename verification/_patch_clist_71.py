for n in range(mx, 1, -1):
    old_h = "### 1.{} ".format(n)
    new_h = "### 1.{} ".format(n + 1)
    hit = [i for i, s in enumerate(lines) if s.startswith(old_h)]
    if len(hit) != 1:
        print("  [XX] 顺延 1.{} 命中 {} 行".format(n, len(hit)))
        BAD += 1
    else:
        lines[hit[0]] = new_h + lines[hit[0]][len(old_h):]
        OK += 1
