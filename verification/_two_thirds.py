import math

c = 299792458.0
G = 6.67430e-11
hbar = 1.054571817e-34
eV = 1.602176634e-19
lP = math.sqrt(hbar * G / c ** 3)
Mpc = 3.0856775814913673e22
H0 = 67.66 * 1e3 / Mpc

rho_crit = 3 * H0 ** 2 / (8 * math.pi * G)
rho_crit_E = rho_crit * c ** 2
EP = math.sqrt(hbar * c ** 5 / G)
MPL_eV = EP / eV
eps0, beta = 7.7e-20, 0.615
Ec_eV = MPL_eV * eps0 ** (1 / beta)
rhoL_Ec = (Ec_eV * eV) ** 4 / (hbar * c) ** 3

OM_b, OM_cdm, OM_L, OM_m = 0.0493, 0.2618, 0.6889, 0.3111
TWOTHIRD = 2.0 / 3.0


def line(t):
    print("\n" + "=" * 74)
    print(t)
    print("=" * 74)


def chk(name, got, want, tol=1e-9):
    ok = abs(got - want) <= tol * max(1.0, abs(want))
    print("  [%s] %-44s got=%.10g  want=%.10g" % ("OK" if ok else "XX", name, got, want))
    return ok


# ---------------------------------------------------------------- TT-1
line("TT-1  2/3 的出处：跨枝守恒流（原文 776–783 / 1366–1390 页）")
ser = sum((-0.5) ** k for k in range(200))
chk("级数 1 − 1/2 + 1/4 − … = 2/3", ser, TWOTHIRD, 1e-12)
print("  守恒流：dJ₊/dt = -⅓J₊ + ⅓J₋ + ερ ；稳态 J₊=(1/2+ε)ρ、J₋=(1/2−ε)ρ")
print("  每枝 1/3 跨枝转移 ⟹ 本枝残余 **2/3**")
print("  原文明确：2/3 是**跨枝转移后残余的比例**，不是正枝固有比例")

# ---------------------------------------------------------------- TT-2
line("TT-2  2/3 = 0.666667 与各 Ω 对照：谁最接近？")
print("  组分            观测 Ω      2/3        偏差")
rows = [("暗能量 Ω_Λ", OM_L), ("总物质 Ω_m", OM_m), ("暗物质 Ω_cdm", OM_cdm),
        ("重子 Ω_b", OM_b), ("暗物质+暗能量", OM_cdm + OM_L)]
for name, om in rows:
    print("  %-16s %-10.4f %-10.6f %+8.1f%%" % (name, om, TWOTHIRD,
                                                100 * (TWOTHIRD - om) / om))
print()
print("  ⟹ **暗能量 Ω_Λ 是唯一接近的**：2/3 vs 0.6889，差 **3.23%**。")
print("  ⟹ 原文把它安在「暗物质占 2/3」上：2/3 vs 0.2618，**差 155%**（2.55 倍）。")
print("  ⟹ 批5 §3.3 与批7 第 12 号存疑，根源很可能是**安错了组分**。")

# ---------------------------------------------------------------- TT-3
line("TT-3  等价形式（与我上一轮 CR-3 的 H²/(4πG) 是同一式）")
rho_23 = TWOTHIRD * rho_crit_E
rho_4pi = H0 ** 2 / (4 * math.pi * G) * c ** 2
chk("(2/3)ρ_crit = H²/(4πG)", rho_23, rho_4pi, 1e-12)
print("  ρ_Λ = (2/3)ρ_crit = H²/(4πG) = %.6g J/m³" % rho_23)
print("  ⟹ 上一轮 CR-3 说「4π 没有机制」——**机制在原文里：4π 就是 2/3 的等价写法**")
print("     Ω_Λ = (2/3)ρ_crit / ρ_crit = 2/3  ⟺  ρ_Λ = H²/(4πG)")

# ---------------------------------------------------------------- TT-4
line("TT-4  O-Λ 剩余因子：从 23.76 降到 1.033")
om_Ec = rhoL_Ec / rho_crit_E
print("  E_c⁴ 路线      ：Ω_Λ = %.5f  ⟹ 差 %.2f 倍" % (om_Ec, OM_L / om_Ec))
print("  (2/3)ρ_crit 路线：Ω_Λ = %.5f  ⟹ 差 %.3f 倍（**%.2f%%**）"
      % (TWOTHIRD, OM_L / TWOTHIRD, 100 * (OM_L - TWOTHIRD) / TWOTHIRD))
print("  ⟹ 若采纳跨枝 2/3 机制，**O-Λ 的剩余因子从 23.76 → 1.033**。")
print("  ⟹ 这是今晚所有候选里唯一把 Ω_Λ 做到 5%% 以内的。")

# ---------------------------------------------------------------- TT-5
line("TT-5  若 2/3 归 Λ，则 1/3 归谁？")
