# -*- coding: utf-8 -*-
"""
第 33 轮：B2 软肋的定量检验 —— 权重 w 扫描
背景：第 32 轮取读法 B2，唯一软肋是「C-b / C-c 是否属于跨层搬运」
      （把第 20 轮衬底占位动力学的「真空 / 湮灭中不占权重」搬到面元状态计数层）。
办法：在两类模型里显式引入权重 w，看 Hawking 温度约束能把 w 压到多窄。
  模型 A（第 19 轮）：1-of-4 方向 × 内部四态，
        内部分布 = {正,负} 共占 (1-w)，{湮灭中,真空} 共占 w（各半）
  模型 S（槽模型）  ：4 个平面内连接，每槽 ∈ {正, 负, 空}，空槽权重 w
只用标准库。正文引号一律用中文引号。
"""
import math as m

C_MS = 2.99792458e8
G_SI = 6.67430e-11
H_PLANCK = 6.62607015e-34
HBAR = H_PLANCK / (2 * m.pi)
K_B = 1.380649e-23
M_SUN = 1.98892e30          # 与第 15/25/31/32 轮一致

NCHK = [0, 0]


def line(tag):
    print("\n" + "=" * 76)
    print("  " + tag)
    print("=" * 76)


def chk(name, got, want, rtol=1e-9):
    if isinstance(got, bool) or isinstance(want, bool):
        ok = bool(got) == bool(want)
        got_s, want_s = str(got), str(want)
    else:
        ok = abs(got - want) <= rtol * max(1.0, abs(want))
        got_s, want_s = "%.12g" % got, "%.12g" % want
    NCHK[0] += 1
    if not ok:
        NCHK[1] += 1
    print("  [%s] %-50s got=%s want=%s" % ("OK" if ok else "XX", name, got_s, want_s))
    return ok


def show(name, val, fmt="%.12g"):
    print("       %-44s %s" % (name, fmt % val))


def h2(w):
    """二元 Shannon 熵（自然对数）"""
    if w <= 0.0 or w >= 1.0:
        return 0.0
    return -w * m.log(w) - (1 - w) * m.log(1 - w)


LN16 = m.log(16)
LN8 = m.log(8)
COMP = 4 * LN16                      # 相干压缩因子 = 16 ln2 = 11.0904
T_STD = HBAR * C_MS ** 3 / (8 * m.pi * G_SI * M_SUN * K_B)

print("=" * 76)
print("  第 33 轮：权重 w 扫描 —— B2 的软肋（C-b / C-c 跨层性）有多硬")
print("=" * 76)

# ================================================================== W-1
line("W-1  模型 A 的熵：H_A(w) = ln 8 + h₂(w)")


def H_A(w):
    # 方向 4 等概率 ⟹ ln4；内部：{正,负} 各 (1-w)/2，{湮灭中,真空} 各 w/2
    return m.log(4) + h2(w) + m.log(2)


show("H_A(0)    （真空/湮灭中零权重）", H_A(0.0))
show("  ln 8 =", LN8)
chk("H_A(0) = ln 8（A′：8 态 = 3 bits）", H_A(0.0), LN8, 1e-12)
show("H_A(0.5)  （四态等权）", H_A(0.5))
chk("H_A(0.5) = ln 16（读法 A 原样）", H_A(0.5), LN16, 1e-12)

# ================================================================== W-2
line("W-2  模型 A：Hawking 温度偏差随 w 的扫描")


def dev_A(w):
    """温度相对偏差 = S_req/S(w) − 1"""
    return LN16 / H_A(w) - 1.0


print("      w         H_A (nats/面元)   S/S_req     温度偏差")
for w in (0.0, 0.05, 0.1, 0.2, 0.3, 0.4, 0.45, 0.5):
    print("      %-9.3f %-16.6f %-12.6f %+.4f%%"
          % (w, H_A(w), H_A(w) / LN16, 100 * dev_A(w)))
show("w = 0 时的 T / K", T_STD * (1 + dev_A(0.0)), "%.6e")
chk("w = 0 的偏差 = +33.3333%（与第 32 轮一致）", dev_A(0.0), 1.0 / 3.0, 1e-12)


def bisect(f, lo, hi, tol=1e-12):
    flo, fhi = f(lo), f(hi)
    for _ in range(200):
        mid = 0.5 * (lo + hi)
        fm = f(mid)
        if (flo <= 0 <= fm) or (fm <= 0 <= flo):
            hi, fhi = mid, fm
        else:
            lo, flo = mid, fm
        if hi - lo < tol:
            break
    return 0.5 * (lo + hi)


# 偏差 ≤ +1% 所需的 w
w_1pct = bisect(lambda w: dev_A(w) - 0.01, 1e-12, 0.5)
w_5pct = bisect(lambda w: dev_A(w) - 0.05, 1e-12, 0.5)
show("温度偏差 ≤ +1% 所需的最小 w", w_1pct, "%.6f")
show("温度偏差 ≤ +5% 所需的最小 w", w_5pct, "%.6f")
print("""
      ⟹ **在模型 A 里，Hawking 温度把 w 死死顶在 0.5 附近**：
         想让温度偏差进 1%%，w 必须 ≥ %.3f（即「真空+湮灭中」要占约 %.0f%% 的权重）。
         而 C-b（满占位 f=1，无空格点）与 C-c（湮灭中零测度）要求 **w = 0**。
         两者相距 %.3f，不可调和 ⟹ **模型 A 被双重夹死**。"""
      % (w_1pct, 100 * w_1pct, w_1pct - 0.0))

# ================================================================== W-3
line("W-3  槽模型 S：4 个平面内连接，每槽 ∈ {正, 负, 空}，空槽权重 w")


def H_S(w):
    # 每槽：{正,负} 各 (1-w)/2，空 w
    return 4.0 * (h2(w) + (1 - w) * m.log(2))


show("H_S(0)    （无空槽 = 读法 B2）", H_S(0.0))
chk("H_S(0) = 4 ln 2 = ln 16 ✓（正是 B2 的 16 态）", H_S(0.0), LN16, 1e-12)
show("H_S(1/3)  （三值等权）", H_S(1.0 / 3.0))
chk("H_S(1/3) = 4 ln 3 = ln 81（81 态）", H_S(1.0 / 3.0), 4 * m.log(3), 1e-12)

# ================================================================== W-4
line("W-4  槽模型：解 H_S(w) = ln 16，看有几个物理解")


def dev_S(w):
    return LN16 / H_S(w) - 1.0


print("      w         H_S (nats/面元)   S/S_req     温度偏差")
for w in (0.0, 0.02, 0.05, 0.1, 0.2, 1.0 / 3.0, 0.5, 0.7, 0.772, 0.8):
    print("      %-9.3f %-16.6f %-12.6f %+.4f%%"
          % (w, H_S(w), H_S(w) / LN16, 100 * dev_S(w)))
print("      ⟹ H_S(w) = ln16 在 (0,1) 上有**两个**根：w = 0（平凡解）与一个大根。")
w_big = bisect(lambda w: H_S(w) - LN16, 0.5, 0.95)
show("大根 w₂（数值求解）", w_big, "%.6f")
chk("大根处 H_S = ln 16", H_S(w_big), LN16, 1e-9)
show("  ⟹ 该处空槽占比", w_big, "%.4f")
print("      ⟹ 但 w₂ ≈ %.3f 意味着 **%.0f%% 的平面内连接是空的**，" % (w_big, 100 * w_big))
print("         与 C-b（满占位 f = 1）直接冲突 ⟹ **排除，只剩 w = 0**。")
chk("大根与满占位冲突（w₂ > 0.5）", float(w_big > 0.5), True)

# ================================================================== W-5
line("W-5  两个模型的对照：谁的 w 与 C-b / C-c 相容")

print("""
      模型             BH 熵（H = ln16）要求的 w      C-b / C-c 要求的 w      相容?
      ───────────────────────────────────────────────────────────────────────
      A（1-of-4 × 四态）  w = 0.500（唯一）              w = 0                 ❌ 相距 0.500
      S（4 槽 × {正,负,空}） w = 0（或 %.3f，后者与 C-b 冲突）  w = 0          ✅ 相容"""
      % (w_big,))
show("A 模型的 w 落差（BH 要求 − C-b/C-c 要求）", 0.5 - 0.0, "%.4f")
show("S 模型的 w 落差", 0.0, "%.4f")
chk("相容者 = 槽模型 S 的 w = 0（即读法 B2）", float(H_S(0.0) == LN16), True)

# ================================================================== W-6
line("W-6  软肋检验的结论")

print("""
  ✅ **软肋解除，而且是以「不需要搬运」的方式解除的。**
     第 32 轮担心的是：B2 依赖把第 20 轮衬底动力学的「真空不占权重」搬到面元计数层。
     本轮的 w 扫描说明 **B2 根本不需要这一步**：

       · 在槽模型里显式留出一个「空槽」态并赋予权重 w，BH 熵要求 H_S(w) = ln16；
         解只有 w = 0（平凡解）与 w ≈ %.3f（后者意味着 %.0f%% 的连接是空的，被 C-b 排除）。
       · **w = 0 不是"从衬底搬来的假设"，而是 BH 熵 + 满占位共同解出来的结果。**
       · 反过来，模型 A 的 w 被 BH 锁在 **0.500**，而 C-b/C-c 要 **0**——
         落差 0.5，对应温度偏差 +33.33%%。**A 是被两头夹死，不是"略差"。**

  ✅ **副产品：读法 B2 的「每条平面内连接恒有通量」现在有了出处**——
     它由 (i) BH 熵定标 + (ii) C-b 满占位 共同确定，不再是无依据的构造假设。
     其物理链条也直接：满占位 ⟹ 每个格点被占 ⟹ 每条键都承载通量 ⟹ 4 条平面内连接全活；
     再由 A1 的 50:50，每条连接各取正支 / 负支 ⟹ 2^4 = 16。

  ⚠️ **仍开放**：① 槽模型的「空槽率」w 与衬底占位率 f 是否同一个量，未独立论证
     （本轮默认同一）；② w = 0 是 BH 的**精确**要求，若将来压缩因子被重新导出，
     约束会随之改变；③ B1（连接 / 不连接）仍未彻底排除（只因 C-e 落选）。
""" % (w_big, 100 * w_big))

print("=" * 76)
print("  检查项：%d    失败项：%d" % (NCHK[0], NCHK[1]))
print("=" * 76)
