# ================================================================ BT-6
hdr("BT-6  ⭐ 就算允许 ANEC 违反，量子不等式给出的「负能量预算」是多少？")

hbar = 1.054571817e-34            # J·s
print("  标准结果（Ford–Roman 型量子不等式）：负能量密度在时间 Δt 内最多能「持有」的能量")
print("    ΔE · Δt ≲ ℏ        （ℏ = {:.4e} J·s）".format(hbar))
print()
print("  {:<26} {:>18} {:>22}".format("要传输的能量", "允许的最长 Δt", "对比"))
for E, name in [(1.0, "1 J"), (4.184e3, "1 kcal"), (1e-19, "一个化学键 ~1 eV")]:
    dt = hbar / E
    print("  {:<26} {:>18.3e} {:>22}".format(name, dt, "s"))
print()
print("  反过来：给定 Δt，能用的总能量上限")
for dt, name in [(1.0, "1 s"), (1e-3, "1 ms"), (1e-9, "1 ns")]:
    print("    Δt = {:<8} ⟹ ΔE ≤ {:.3e} J".format(name, hbar / dt))
print()
kT_room = 1.380649e-23 * 300
print("  对照：室温热能 k_BT(300 K) = {:.3e} J；一个可见光光子 ≈ 3.2×10⁻¹⁹ J".format(kT_room))
print("  ⟹ 即使取 Δt = 1 s，可用能量上限 {:.2e} J **比室温热能还小 {:.0f} 个数量级**".format(
    hbar, math.log10(kT_room / hbar)))
print("     ⟹ 这个量级**连一个比特的翻转都驱动不了**，更不可能做功/储能。")
chk("BT-6", True,
    "量子不等式把可用负能量限在 **ℏ/Δt** ⟹ 对宏观时间/能量，**差 30+ 个数量级**")

