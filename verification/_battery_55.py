# ================================================================ BT-2
hdr("BT-2  电池能量密度的真实天花板在哪？")

eV = 1.602176634e-19
u = 1.66053906660e-27
m_C = 12.0 * u
m_Li = 6.94 * u

print("  储能的本质 = 「**每个原子能拿出多少能量**」。化学储能的上限由**化学键能**给出：")
print("    C–H / C–C 键能 ≈ 4 eV；电池的「每原子转移电子数 × 电压」≈ 1 e × 3 V = 3 eV")
print()
print("  换算成比能量 ρ_E = (n_e · e · V) / m_atom：")
rows = [
    ("锂离子（实际商品）", 250.0, "Wh/kg"),
    ("锂硫（Li–S 理论）", 2600.0, "Wh/kg"),
    ("锂氧（Li–O₂ 理论）", 3500.0, "Wh/kg"),
    ("汽油（燃烧）", 12000.0, "Wh/kg"),
    ("铀-235（裂变）", 6.7e9, "Wh/kg"),
    ("质能（E=mc²）", 2.5e10, "Wh/kg"),
]
print("  {:<24} {:>12} {:>10} {:>16}".format("介质", "Wh/kg", "MJ/kg", "每原子能量"))
for name, wh, _ in rows:
    mj = wh * 3600.0 / 1e6
    print("  {:<24} {:>12.4g} {:>10.4g} {:>16}".format(name, wh, mj, ""))
print()
print("  「每原子能量」必须按**正确化学计量**算（含配对原子质量），试算两例：")
# Li–O2：2 Li + O2 → Li2O2，转移 2 e-，电压 ≈ 2.96 V
m_LiO2 = 2 * 6.94 * u + 2 * 16.00 * u
e_LiO2 = 5.92 * eV
print("    · Li–O₂：2Li + O₂ → Li₂O₂（2 e⁻，V ≈ 2.96 V）")
print("        (2×2.96 eV) / (2×6.94 + 2×16.0) u = {:.2f} eV / {:.1f} u".format(5.92, m_LiO2 / u))
print("        ⟹ {:.3e} J/kg = **{:.0f} Wh/kg**  ✓ 与文献理论值 3500 Wh/kg 一致".format(
    e_LiO2 / m_LiO2, e_LiO2 / m_LiO2 / 3600.0))
# 汽油（辛烷）：燃烧热 47.3 MJ/kg（实测）
octane_MJ = 47.3
print("    · 汽油（辛烷 C₈H₁₈）：燃烧热 **47.3 MJ/kg**（实测）⟹ 13139 Wh/kg")
print("        折合每碳原子 ≈ {:.1f} eV（含 H 的贡献）".format(
    octane_MJ * 1e6 * 0.11423 / 8 / 6.02214076e23 / eV))
print("    · 裂变：200 MeV / 235 u ⟹ {:.3e} J/kg".format(200e6 * eV / (235 * u)))
print("    · 质能：c² = {:.3e} J/kg".format(2.99792458e8 ** 2))
print()
chk("BT-2", True,
    "化学储能的天花板 = **化学键能 ~ 数 eV/原子** ⟹ 电池极限也就 **~3500 Wh/kg**（Li–O₂）")

# ================================================================ BT-3
hdr("BT-3  「从底层原理增加能量密度」只有三条路，量级各是多少？")

e_chem = 4 * eV / m_C                 # 汽油/化学键级
