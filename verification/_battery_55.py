e_mc2 = 2.99792458e8 ** 2             # 质能
print("  {:<34} {:>14} {:>10}".format("路径", "J/kg", "相对化学"))
for name, v in [("① 更好的化学（材料筛选/结构设计）", e_chem),
                ("② 核（裂变）", e_fission),
                ("③ 质能转换（E=mc²）", e_mc2)]:
    print("  {:<34} {:>14.3e} {:>10.3g}×".format(name, v, v / e_chem))
print()
print("  ⟹ **只有 ②③ 是量级突破，而它们都不属于化学/材料学**。")
print("    ① 的每一分提升都来自**量子化学计算（DFT）+ 实验筛选** —— 那是成熟领域，")
print("    本框架对它**零贡献**（BT-1）。")
chk("BT-3", True,
    "量级突破只能来自**核或质能**；化学路径的提升靠 **DFT + 材料筛选**（非本框架领域）")

