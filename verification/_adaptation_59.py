print("\n[AD-4] ★ 最优维护间隔 —— 是不是「越勤越好」？")
print("      简化模型（线性退化 + 完全恢复 + 故障成本）：")
print("        · 退化率 λ（单位时间故障倾向）")
print("        · 每次维护成本 C_m；一次故障的成本 C_f")
print("        · 每 t 维护一次 ⟹ 单位时间成本 `C(t) = C_m/t + C_f·λ·t/2`")
print("        · 求极值：`dC/dt = 0` ⟹ **`t* = √(2·C_m/(C_f·λ))`**")
print("      " + "-" * 62)
print("      {:<12} {:<12} {:<12} {:>14} {:>16}".format("λ (/月)", "C_m", "C_f", "最优间隔 t*", "每月成本 C(t*)"))
for lam, Cm, Cf in [(0.01, 1.0, 100.0), (0.01, 1.0, 1000.0), (0.05, 1.0, 100.0), (0.2, 1.0, 100.0)]:
    tstar = math.sqrt(2 * Cm / (Cf * lam))
    cost = Cm / tstar + Cf * lam * tstar / 2
    print("      {:<12} {:<12} {:<12} {:>13.3f} {:>16.4f}".format(lam, Cm, Cf, tstar, cost))
print("      ⟹ ⭐ 三个结论：")
print("         (i) **存在最优点**（t* 有限）—— 不是「越勤越好」：")
print("             维护太勤 ⟹ `C_m/t` 项爆炸（**维护本身的开销**）")
print("             维护太疏 ⟹ 故障成本项爆炸")
print("         (ii) **`t* ∝ 1/√λ`**：环境退化快 ⟹ 维护更勤，但是**平方根关系**，")
print("              **不是正比** —— 退化率变 4 倍，维护频率只需变 2 倍")
print("         (iii) `t* ∝ √(C_m/C_f)`：故障的代价**相对**越大，越该勤（也走 √）")
print("      ⟹ 用户的「因变化而变化」方向对，但**强度被高估了** —— 是 **√**，不是线性。")
chk("AD-4", True,
    "★ 最优间隔 **t* = √(2C_m/(C_f λ))**：**存在最优点**；且 t* ∝ **1/√λ**（不是正比）")

