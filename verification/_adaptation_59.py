print("      在**所有可能的目标函数上取平均**，**任意两个优化算法的期望性能完全相同**。")
print("      ⟹ 推论：**不存在一个对所有问题都最优的固定算法**。")
print("      ⟹ 用户的「不要奢望一个恒定的操作流程能适应一切变化」**得到了数学支撑**。")
