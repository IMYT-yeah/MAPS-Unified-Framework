print("\n[AD-5] ★ 探索-利用：最优的「改变」量有界")
print("      **多臂老虎机**（K 个臂、T 轮）：任何策略的**累积遗憾**（regret）")
print("      下界为 `Ω(√(K·T))`；最优算法（UCB / Thompson）达到 `O(√(K·T·log T))`。")
print("      " + "-" * 62)
print("      {:<10} {:<12} {:>16} {:>16} {:>12}".format("K 臂", "T 轮", "最优遗憾 ~√(KT)", "纯探索代价 ~T", "比值"))
for K, T in [(10, 100), (10, 10000), (100, 10000)]:
    opt = math.sqrt(K * T)
    naive = T
    print("      {:<10} {:<12} {:>16.1f} {:>16} {:>12.1f}".format(K, T, opt, naive, naive / opt))
print("      ⟹ ⭐ **最优的「探索（改变）量」随 T 只按 `√T` 增长**，不是线性增长：")
print("         · **一次都不改**（纯利用）⟹ 环境变了就失效（用户担心的那个）")
print("         · **一直改**（纯探索）⟹ 代价 ~T，比最优差 **√T 倍**（T = 10⁴ 时差 **100 倍**）")
print("         · **最优 ≈ 按 √T 的量去探索** ⟹ 「**偶尔改变**」，不是「**频繁改变**」")
chk("AD-5", True,
    "★ 最优探索量 ~**√(KT)**；「一直改」比最优差 √T 倍（T=10⁴ 时差 100 倍）")

