print("      ⟹ 步骤 ③ 的下界 = Landauer：擦除 1 比特 ≥ `k_B·ln2` = {:.4e} J/K".format(Sbit))
print("      ⟹ 所以**「改变」不是免费的动作** —— 它有自己的熵账单。")
