"""
第 29 轮：§4.10「六处 4」的分层判定 —— 哪些同源，哪些只是 d = 3 的后果
SF-1 … SF-7，只用标准库。
"""
import math as m

CHECKS = []
def chk(name, got, want, tol=1e-12):
    ok = abs(got - want) <= tol * max(1.0, abs(want))
    CHECKS.append((name, ok))
    print("  [%s] %-58s got=%.10g  want=%.10g" % ("OK" if ok else "XX", name, got, want))
    return ok

def show(name, val):
    print("        %-58s = %.10g" % (name, val))

def line(t):
    print("\n" + "=" * 80)
    print(t)
    print("=" * 80)

# ================================================================== SF-1
line("SF-1  六处「4」的出处追溯（本轮逐一核查）")
print("""
  | # | 处 | 论文标注 | 追溯到的机制 | 独立? |
  |---|---|---|---|---|
  | ① | 表面诸元 4 邻居 | 观测者几何，本框架**推论** | §4.9 引理 1【设定】"平面内 4 方向" = (d−1) 维表面网格的配位 2(d−1) | **独立** |
  | ② | Clifford 4 分量 | 内空间，本框架**设定** | 论证 4：Cl(1,3) 表示维数 = 2^⌊D/2⌋（D = 时空维数） | **独立** |
  | ③ | 通量管相干截面 4l_P² | k 模型 | Nyquist：模式数 = k 需 ≥k 采样点 | 同源(LST) |
  | ④ | 每 4 面元 1 比特 | 本框架**设定** | 同 ③（= 1/(4l_P²) 的倒数） | 同源(LST) |
  | ⑤ | 挂谷 packing 1/4 | 本框架**推论** | §4.10 命题 5：链条起点 = 定理 1（k≥4） | 同源(LST) |
  | ⑥ | 正四面体 4-方向簇 | Tammes n=4 | §4.10 定理 1+2 = **LST/Borsuk** | 同源(LST) |
  ⟹ **初步分层**：③④⑤⑥ 锚在 k = 4（= LST/Borsuk）；**①② 是独立来源**。
  ⟹ 换句话说，「六处同源」至多能说成「**四会同源 + 两处独立**」。""")

# ================================================================== SF-2
line("SF-2  扰动试验：改变空间维数 d，看三组机制各自怎么变")

def k_lst(d):
    """S^{d-1} 上方向覆盖所需的方向数 = (d-1) + 2 = d + 1（LST/Borsuk 数）"""
    return d + 1

def n_surf(d):
    """(d-1) 维超立方表面的配位数 = 2(d-1)"""
    return 2 * (d - 1)

def clifford(d):
    """时空维数 D = d+1，Cl(1, D-1) 的不可约表示维数 = 2^floor(D/2)"""
    D = d + 1
    return 2 ** (D // 2)

print("  | 空间维 d | ① 表面邻居 2(d−1) | ② Clifford 2^⌊(d+1)/2⌋ | ③④⑤⑥ k = d+1 |")
print("  |---|---|---|---|")
tab = {}
for d in (2, 3, 4, 5, 6):
    a, b, c = n_surf(d), clifford(d), k_lst(d)
    tab[d] = (a, b, c)
    mark = " **← 三者重合**" if a == b == c else ""
    print("  | %d | %d | %d | %d |%s" % (d, a, b, c, mark))
print("""
  ⟹ 只有 **d = 3** 让三组同时等于 4。（d = 2 给 (2,2,3)；d = 4 给 (6,4,5)；d = 5 给 (8,8,6)）
  ⟹ 注意这不是"某两处碰巧相等"，而是**三个完全不同的函数在 d = 3 处同取 4**。""")

# ================================================================== SF-3
line("SF-3  唯一性：三组相等 ⟹ (n, d) = (4, 3) 是唯一解")
print("""
  设三组共同值为 n，则
    2(d − 1) = n          （①）
    d + 1    = n          （⑥）
  相减：(d+1) − 2(d−1) = 0 ⟹ d + 1 = 2d − 2 ⟹ d = 3 ⟹ n = 4
  再验证 ②：2^⌊(d+1)/2⌋ = 2^⌊4/2⌋ = 2² = 4 = n ✓""")
sol_d = 3
sol_n = 2 * (sol_d - 1)
show("解出的 d", float(sol_d))
show("解出的 n", float(sol_n))
chk("① 与 ⑥ 的交点给 d = 3", float(sol_d), 3.0)
chk("② 在该点也等于 n = 4", float(clifford(sol_d)), float(sol_n))
# 暴力枚举确认唯一（整数解）
found = [d for d in range(2, 200) if n_surf(d) == clifford(d) == k_lst(d)]
show("在 2 ≤ d < 200 内的全部解", float(len(found)))
chk("解唯一 = {3}", float(found[0] if found else -1), 3.0)
print("""
  ⟹ **「表面网格配位数」「内空间表示维数」「方向覆盖数」三者一致 ⟺ d = 3（空间三维）**，
     而且是**唯一解**。也就是说：§4.10 那几处「4」的相等，**实际等价于「空间是三维的」**。""")

# ================================================================== SF-4
line("SF-4  Cl(1, D−1) 表示维数公式的独立核对")
print("""
  已知的低维 Clifford 代数不可约表示维数（Dirac 旋量分量数）：
  D=3（2+1 维）→ 2；D=4（3+1 维）→ 4；D=5（4+1 维）→ 4；D=6（5+1 维）→ 8。""")
for D, expect in ((3, 2), (4, 4), (5, 4), (6, 8)):
    got = 2 ** (D // 2)
    show("D = %d ⟹ 2^⌊D/2⌋" % D, float(got))
    chk("  D = %d 的旋量分量数" % D, float(got), float(expect))
print("  ⟹ 公式正确。**Cl(1,3) 的 4 来自时空维数 4，与 LST 的 4 是两回事。**")

# ================================================================== SF-5
line("SF-5  同源判定的结论：分层，而不是「六处同源」")
print("""
  | 组 | 处 | 底层机制 | 随 d 变化 |
  |---|---|---|---|
  | **LST 组** | ③ 4l_P²、④ 每 4 面元 1 比特、⑤ 挂谷 1/4、⑥ 正四面体 4 方向 | S² 覆盖（LST/Borsuk）⟹ k = d+1 | 3, **4**, 5 |
  | **独立组 1** | ① 表面 4 邻居 | (d−1) 维表面网格配位 = 2(d−1) | 2, **4**, 6 |
  | **独立组 2** | ② Clifford 4 分量 | Cl(1,d) 表示维数 = 2^⌊(d+1)/2⌋ | 2, **4**, 4 |
  ⟹ **三组机制互不相干，但在 d = 3 处同取 4。**
  ⟹ 因此「六处 4 同源」的**正确读法**是：
     · 其中 4 处（③④⑤⑥）确实同源于 **k = 4（LST/Borsuk）**；
     · 另 2 处（①②）是**独立机制**，它们的 4 是 **d = 3 的后果**；
     · 而"三组在 d = 3 处重合"这件事，**底层等价于"空间三维"** —— 后者在框架里是【设定】。""")

