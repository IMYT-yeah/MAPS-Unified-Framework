# -*- coding: utf-8 -*-
"""第 52 轮：工程期望清单补丁（T-9 裁决 + T-10 登记 + 候选池）。"""

import io
import os
import re

P = os.path.join(os.path.dirname(os.path.abspath(__file__)), "工程期望清单.md")
OK = [0]
FAIL = [0]


def sub_once(old, new, tag):
    t = io.open(P, encoding="utf-8").read()
    n = t.count(old)
    if n != 1:
        FAIL[0] += 1
        print("  [XX] {:<28} 命中 {} 次 —— 拒绝".format(tag, n))
        return False
    io.open(P, "w", encoding="utf-8").write(t.replace(old, new, 1))
    OK[0] += 1
    print("  [OK] {:<28} 已改".format(tag))
    return True


# ---------------------------------------------------------------- 1. 顺延
L = io.open(P, encoding="utf-8").read().split("\n")
idx = [i for i, s in enumerate(L) if s.startswith("### 1.")]
print("=== 1. 小节顺延（降序；跳过「讨论纪要」）===")
for i in sorted(idx, reverse=True):
    if "讨论纪要" in L[i]:
        print("  [跳过] {}（讨论纪要不参与轮次顺延）".format(L[i][:30]))
        continue
    m = re.match(r"### 1\.(\d+)\s+(.*)", L[i])
    new = "### 1.{} {}".format(int(m.group(1)) + 1, m.group(2))
    print("  [OK] 行 {:>4}：{:<22} → {}".format(i + 1, L[i][:22], new))
    L[i] = new
    OK[0] += 1
io.open(P, "w", encoding="utf-8").write("\n".join(L))

# ---------------------------------------------------------------- 2. 新小节
NEW_SEC = """### 1.2 第 52 轮新增

| 标识 | 条目 | 类型 | 内容（含「诚判」） | 评级 |
|---|---|---|---|---|
| **T-9** | ~~张力：观测者的 0.25 纳特 vs 衬底的 H/N → 0~~ | **✅ 已裁决** | 裁决为「**观测钉住的组合 ＋ 无机制的拆分**」：① 乘积「每 4l_P² = 1 纳特」由 **Hawking 温度**钉住（本轮复算 6.16865×10⁻⁸ / 8.89948×10⁻⁸ K，偏差 **+44.27%** 逐位一致）；② 拆成「4 面元/单元 × 1 纳特/单元」是**不可观测的因式分解**（(a,b) = (4,1)/(2,0.5)/(8,2)/… 给**同一个**观测量）；③ 外加设定「格距 = l_P」。⟹ 四类判定 = **半拟合 / 一致性**（**非**真预言、**非**纯公设）。 | — |
| **T-10** | **是否把「格点离散结构 ↔ 面积律」整条链登记为「框架不覆盖」** | **张力（未裁决）** | 第 46–52 轮共**七轮**都在这一条链上，结论一路**负面**：**无等式**（第 51 轮）、**无机制**（a = 4 是设定）、只余一条**实际上不可证伪**的不等式 `H/N ≤ 0.25`（真实黑洞余量 ≈ 10⁵⁰）。⟹ 是否该**正式登记为不覆盖**、把资源换到 S-6 FQH 的 ε 项（清单唯一 ★★★ 且框架**独有**）。⚠️ 这与第 39 轮 N-1「在衬底里找 5.545」是**同一类陷阱的第三次出现**。 | — |

"""
sub_once("### 1.3 第 51 轮新增", NEW_SEC + "### 1.3 第 51 轮新增", "插入 1.2 第52轮新增")

# ---------------------------------------------------------------- 3. 轮次记录
OLD = ("| **第 51 轮** | **I-13 结项** + **增量 1 条**（N-13 **负面**）+ **更正 1 条**（C-3）+ **张力 1 条**（T-9）"
       " | 由「转向机制一侧」衍生：")
i = io.open(P, encoding="utf-8").read().find(OLD)
t = io.open(P, encoding="utf-8").read()
j = t.find("\n", i)
anchor = t[i:j]
NEW = anchor + "\n" + ("| **第 52 轮** | **裁决 T-9** + **新张力 T-10** | 由「裁决 T-9」衍生：B5 的 0.25 = "
                       "**观测钉住的组合**（Hawking 温度判别式复算，+44.27% 逐位一致）＋ **无机制的拆分**"
                       "（观测只钉住 b/a = 0.25，五组 (a,b) 同观测量）⟹ 四类判定 = **半拟合 / 一致性**；"
                       "该链**收口**，并登记 T-10「是否整条链登记为框架不覆盖」 |")
sub_once(anchor, NEW, "轮次记录加第52轮")

# ---------------------------------------------------------------- 4. 候选池
NEW_CAND = """
32. **新增候选（第 52 轮，T-10 的具体化）**：**正式登记「格点离散结构 ↔ 面积律」为框架不覆盖** ——
    并在 §4.8 写明：B5 的 0.25 与衬底之间**只有一条松不等式**（真实黑洞余量 ≈ 10⁵⁰，
    且 N ≤ 41 才违反，而那已是普朗克尺度）⟹ **不构成有效约束**。
    ⚠️ 与第 39 轮 N-1（衬底里找 5.545）、第 51 轮 N-13（找 H/N = 0.25 的等式）**同类**。
33. **新增候选（第 52 轮，回到工程侧）**：**S-6 FQH 的 ε 项预言具体化** ——
    清单里唯一 ★★★，且是框架**独有**的可测项（标准凝聚态无此 ε ≈ 10⁻²⁰ 泄漏项）。
    ⟹ 若 T-10 按「换方向」裁决，这是最值得接手的一项。
"""
t = io.open(P, encoding="utf-8").read()
i = t.find("31. **新增候选（第 51 轮，便宜）**")
if i < 0:
    FAIL[0] += 1
    print("  [XX] 未找到候选池第 31 条")
else:
    j = t.find("\n", i)
    while j + 1 < len(t) and t[j + 1] == " ":
        j = t.find("\n", j + 1)
    t = t[:j + 1] + NEW_CAND + t[j + 1:]
    io.open(P, "w", encoding="utf-8").write(t)
    OK[0] += 1
    print("  [OK] {:<28} 已改".format("候选池加 32 / 33"))

print()
print("=" * 78)
print("清单补丁汇总：成功 {} 项，失败 {} 项".format(OK[0], FAIL[0]))
print("=" * 78)
