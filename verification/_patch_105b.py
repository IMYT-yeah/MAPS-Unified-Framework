def wr(p, s):
    io.open(p, "w", encoding="utf-8").write(s)


def sub(p, old, new, tag):
    s = rd(p)
    n = s.count(old)
    if n != 1:
        BAD.append("{} 命中 {}".format(tag, n)); return
