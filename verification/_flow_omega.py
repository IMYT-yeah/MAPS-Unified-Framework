# -*- coding: utf-8 -*-
"""
守恒流方程能推出 Ω_Λ = 2/3 吗？（2026-09-17）
================================================
原文（批05 §1.1，776–783 页）：
    dJ₊/dt = -⅓J₊ + ⅓J₋ + ερ
    dJ₋/dt = -⅓J₋ + ⅓J₊ + ερ
    声称稳态解 J₊_ss = (1/2+ε)ρ、J₋_ss = (1/2−ε)ρ
另：§1.2 —— 每枝 1/3 跨枝转移 ⟹ 本枝**残余 2/3**

FL-1  严格解这个 ODE 系统：有没有稳态？
FL-2  原文那个"稳态解"是不是这个 ODE 的不动点？
FL-3  加上归一化 J₊+J₋=ρ 后的真正不动点是多少？
FL-4  "2/3 残余"与"稳态占据"是同一个量吗？
FL-5  若强行取 2/3：与观测差多少？另一半 1/3 归谁？
"""
import math

c = 299792458.0
G = 6.67430e-11
Mpc = 3.0856775814913673e22
H0 = 67.66 * 1e3 / Mpc
rho_crit = 3 * H0 ** 2 / (8 * math.pi * G)
OM_L, OM_m, OM_cdm = 0.6889, 0.3111, 0.2618
EPS = 7.7e-20


def line(t):
    print("\n" + "=" * 74)
    print(t)
    print("=" * 74)


def chk(name, got, want, tol=1e-12):
    ok = abs(got - want) <= tol * max(1.0, abs(want))
    print("  [%s] %-46s got=%.10g  want=%.10g" % ("OK" if ok else "XX", name, got, want))
    return ok


# ---------------------------------------------------------------- FL-1
line("FL-1  严格解：令 S = J₊+J₋，D = J₊−J₋")
print("  dS/dt = 2ερ            ⟹ S(t) = S₀ + 2ερt   （**线性增长**）")
print("  dD/dt = -(2/3)D        ⟹ D(t) = D₀ e^{-2t/3}（指数衰减，时标 3/2）")
print("  ⟹ **两枝都带 +ερ 源时，系统没有不动点**（S 一直涨）。")
print("     原文声称的『稳态解』不是这个 ODE 的不动点 —— 见 FL-2。")

# ---------------------------------------------------------------- FL-2
line("FL-2  原文的『稳态解』是 ODE 的不动点吗？")
# 注意：真实 ε=7.7e-20 时 0.5±ε 在双精度下会塌缩成 0.5（灾难性抵消）。
# 这里把 ε 放大到 0.1 做代数等价检验（方程对 ε 是线性的，结论不变）。
print("  ⚠️ 真实 ε=7.7e-20 时 0.5±ε 在双精度下塌缩为 0.5，故放大到 ε=0.1 检验（方程对 ε 线性）")
e = 0.1
rho = 1.0
Jp = (0.5 + e) * rho
Jm = (0.5 - e) * rho
dJp = -(1 / 3) * Jp + (1 / 3) * Jm + e * rho
dJm = -(1 / 3) * Jm + (1 / 3) * Jp + e * rho
print("  代入 J₊=(1/2+ε)ρ、J₋=(1/2−ε)ρ（ε=0.1）：")
print("    dJ₊/dt = %.6f ρ   （应 = 0 才是不动点）" % dJp)
print("    dJ₋/dt = %.6f ρ" % dJm)
print("  解析：dJ₊/dt = (ρ/3)(−2ε) + ερ = **ερ/3 ≠ 0**")
chk("dJ₊/dt = ερ/3", dJp, e / 3, 1e-12)
print("  ⟹ 换算回真实 ε：dJ₊/dt = ερ/3 = %.4g ρ ≠ 0（数值极小但**不为零**）" % (EPS / 3))
print("  ⟹ **原文声称的稳态解不是其自身 ODE 的不动点**（差 ερ/3）。")
print("  ⟹ 这是原文的一处内部不自洽，需在批注中修正（可能漏了汇项 −(J₊+J₋−ρ)/τ）。")

# ---------------------------------------------------------------- FL-3
line("FL-3  加上归一化 J₊+J₋ = ρ 后的真正不动点")
print("  若总量被约束为 ρ（J₊+J₋=ρ），则 D = J₊−J₋，J₊ = (ρ+D)/2")
print("  dD/dt = 2·dJ₊/dt = −(2/3)D + 2ερ  ⟹ 不动点 D* = 3ερ")
print("  ⟹ J₊_ss = (ρ + 3ερ)/2 = ρ(1/2 + 3ε/2)")
print("     原文给的是 ρ(1/2 + ε) —— **差个 3/2 因子**（第二处不自洽）。")
Dstar = 3 * EPS
print("  J₊/ρ = %.10f ；对比原文的 1/2+ε = %.10f" % (0.5 + Dstar / 2, 0.5 + EPS))
print("  ⟹ 无论取哪个，不动点都给出 **≈ 1/2**，不是 2/3。")

# ---------------------------------------------------------------- FL-4
line("FL-4  『2/3 残余』与『稳态占据』是同一个量吗？")
print("  2/3 残余 = 1 − 1/3 = **每周期保留下来的比例**（保留因子）")
print("  1/2 占据 = 两枝对称时的**稳态分支占比**（不动点）")
print("  二者定义完全不同：前者是『走掉 1/3 后剩多少』，后者是『平衡时各占多少』。")
print("  ⟹ **不能把 2/3 直接当成 Ω_Λ 的推导结果** —— 它是保留因子，不是占据比例。")
print()
print("  若误把不动点当 Ω_Λ：Ω_Λ = 1/2 = 0.5，观测 0.6889 ⟹ 差 %.1f%%（**更差**）"
      % (100 * (0.5 - OM_L) / OM_L))
print("  若取保留因子 2/3：Ω_Λ = 0.6667，差 −3.2% ✅")

# ---------------------------------------------------------------- FL-5
line("FL-5  强行取『2/3 残余 = 暗能量』：需要什么假设，对不对得上？")
print("  需要的两步（**第二步是假设，未导出**）：")
print("    (a) 『本应』的总量 = ρ_crit          ← 由已导出的约束方程支持 ✓")
print("    (b) 跨枝转移后**留在本枝**的那份**就是**暗能量  ← **假设，未导出** ✗")
print()
print("  若成立，则另一半 1/3 应归物质：")
print("    Ω_Λ : 2/3 = %.6f  vs 观测 %.4f   偏差 %+.1f%%" % (2 / 3, OM_L, 100 * (2 / 3 - OM_L) / OM_L))
print("    Ω_m : 1/3 = %.6f  vs 观测 %.4f   偏差 %+.1f%%" % (1 / 3, OM_m, 100 * (1 / 3 - OM_m) / OM_m))
print("  ⚠️ 两者偏差**方向相反**（Λ 偏低 3.2%、m 偏高 7.1%）——")
print("     说明不是简单的『分裂点挪了』，两个都对不上同一个偏移。")

line("判决")
print("""  ❌ **Ω_Λ = 2/3 不能从守恒流方程推出。**

   · 方程的不动点给 **1/2**（不是 2/3），对观测差 **−27.4%**。
   · 2/3 是**保留因子**（1−1/3），是另一个量，与稳态占据无关。
   · 把保留因子当作 Ω_Λ 需要额外假设 (b)（『留在本枝的 = 暗能量』），未导出。
   · 且该假设给出的 (2/3, 1/3) 分裂与观测的偏差**方向相反**，不是干净的分裂。

  🔧 顺带查出原文两处内部不自洽（应修正）：
     1. 声称的『稳态解』不是其自身 ODE 的不动点（代入后 dJ₊/dt = ερ/3 ≠ 0）。
     2. 加归一化后的真正不动点是 1/2 + 3ε/2，原文写的是 1/2 + ε（差 3/2）。

  ⟹ 3.2% 的数值接近**目前仍是巧合**，在找到把保留因子接到 Ω_Λ 的机制之前，
     不应把它写成框架预言。
""")
