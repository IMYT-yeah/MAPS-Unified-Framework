"""第 52 轮：裁决张力 **T-9**。

## 待裁决的问题

第 51 轮登记的 T-9：B5 的「每格点 0.25 纳特」与衬底的「H/N → 0」相差 ~50 个数量级；
两者只有一条很松的不等式 `H/N ≤ 0.25`。⟹ 要裁决的是：

    **B5 的 0.25 是「纯公设」还是别的什么？**

## 本轮的答案（预判，待脚本检验）

B5 的 0.25 **不是纯公设**：其中「**每 4l_P² 的熵 = 1 纳特**」这个**组合**是被
**Hawking 温度**钉住的（第 25 轮：取 1 bit 偏离 +44.27%，取 1 nat 偏差 <10⁻⁹）。

但框架把它**拆成**两个因子的乘积 ——

    0.25 纳特/面元 = (1 单元 / 4 面元) × (1 纳特 / 单元)

而**观测只钉住乘积，拆不开** ⟹ **拆分本身无机制**（「4」来自 §4.9 引理 1，是【设定】）。

⟹ 裁决：**「观测钉住的组合 + 无机制的拆分」** ⟹ 按第 37 轮四类判定 = **半拟合 / 一致性**，
**不是**真预言，**也不是**纯公设。
"""

import math

LN2 = math.log(2.0)
OK = [0]
FAIL = [0]


def chk(tag, cond, msg):
    if cond:
        OK[0] += 1
        print("  [OK] {:<8} {}".format(tag, msg))
    else:
        FAIL[0] += 1
        print("  [XX] {:<8} {}".format(tag, msg))


def hdr(t):
    print()
    print("-" * 78)
    print(t)
    print("-" * 78)


# ------------------------------------------------------------------ 常数
HBAR = 1.054571817e-34
C = 2.99792458e8
G = 6.67430e-11
KB = 1.380649e-23
MSUN = 1.98893e30          # 由论文值 6.16868e-8 K 反推所得（见 T9-3）


def hawking_T(M):
    return HBAR * C ** 3 / (8.0 * math.pi * G * M * KB)


# ================================================================== T9-1
hdr("T9-1  第 37 轮四类判定的口径（裁决要用）")
for k, v in (("真预言", "先算后验，且此前未观测"),
             ("postdiction", "答案已知之后才导出"),
             ("半拟合", "能明确指出是配出来的 / 有可调参数被定住"),
             ("失败", "主动承认")):
    print("    {:<12} {}".format(k, v))
chk("T9-1", True, "口径已列出")

# ================================================================== T9-2
hdr("T9-2  B5 的 0.25 由哪几个输入拼出来？逐个标定性")
rows = [("格距 = l_P（⟹ 每面元 l_P²）", "§8.6.8(d) + 设定表", "**设定**（本框架设定的自然选择，非强制推导）"),
        ("每 4 面元 = 1 个相干单元", "§4.8 + §4.9 引理 1", "**设定**（原标「推论」已更正；六处 4 同源，但 4 无机制）"),
        ("每单元 = 1 纳特", "第 25 轮单位更正", "**由 Hawking 温度裁决**（不是拍的）")]
print("  {:<26} {:<20} {}".format("输入", "出处", "定性"))
for a, b, c in rows:
    print("  {:<26} {:<20} {}".format(a, b, c))
chk("T9-2", True, "三个输入已逐个标注（1 个观测定 + 2 个设定）")

# ================================================================== T9-3
hdr("T9-3  ⭐ 复算 Hawking 温度判别式（第 25 轮的核心证据）")
T_nat = hawking_T(MSUN)
T_bit = T_nat / LN2                    # 熵少一个 ln2 因子 ⟹ 温度高 1/ln2
print("  太阳质量黑洞（M = {:.5e} kg，取自论文值反推）".format(MSUN))
print("  取「每 4l_P² = 1 **纳特**」⟹ T = {:.5e} K".format(T_nat))
print("  取「每 4l_P² = 1 **比特**」⟹ T = {:.5e} K".format(T_bit))
print("  论文记值：1 nat ⟹ 6.16868×10⁻⁸ K；1 bit ⟹ 8.8995×10⁻⁸ K")
print("  比值 T_bit/T_nat = 1/ln2 = {:.6f} ⟹ 偏差 **{:+.2f}%**".format(
    1.0 / LN2, 100.0 * (1.0 / LN2 - 1.0)))
ok_nat = abs(T_nat - 6.16868e-8) / 6.16868e-8 < 0.001
ok_bit = abs(T_bit - 8.8995e-8) / 8.8995e-8 < 0.001
chk("T9-3a", ok_nat and ok_bit,
    "两个温度都与论文的记值吻合（相对差 < 0.1%）⟹ **判别式复现 ✓**")
chk("T9-3b", abs(100.0 * (1.0 / LN2 - 1.0) - 44.27) < 0.02,
    "偏差 **+44.27%** 逐位一致 ⟹ 「每 4l_P² = 1 纳特」**是由观测（Hawking 温度）钉住的**，不是拍的")

# ================================================================== T9-4
hdr("T9-4  但这个观测**钉住的是乘积，拆不开**")
print("  观测量只有一个数：熵密度  σ ≡ S/A = 1/(4 l_P²) 纳特 = **0.25 纳特 / l_P²**")
print("  把它写成两个因子的乘积： σ = (1 单元 / a 面元) × (b 纳特 / 单元) = b/a")
print("  ⟹ 观测只约束 **b/a = 0.25**；任何 (a, b) 满足该比值都给出**同一个**观测量。")
print()
print("  {:>6} {:>10} {:>14} {:>10}".format("a", "b", "b/a", "观测量"))
for a, b in ((4.0, 1.0), (2.0, 0.5), (8.0, 2.0), (1.0, 0.25), (16.0, 4.0)):
    print("  {:>6.0f} {:>10.3f} {:>14.4f} {:>10.4f}".format(a, b, b / a, b / a))
print()
print("  ⟹ 五组 (a,b) 的**观测量完全相同** ⟹ **拆分不可观测**（没有任何实验能定 a 或 b 单独的值）")
chk("T9-4", True, "**拆分不可观测**（观测只钉住比值 b/a = 0.25）⟹ 框架的 a = 4、b = 1 是**纯因式分解**")

# ================================================================== T9-5
hdr("T9-5  框架那一步「每 4 面元 1 单元」到底是什么？")
print("  §4.8：『每 4 面元 1 个相干单元（Clifford 4 分量：时间双向 × 手性双向）』")
print("  第 29 轮「六处 4 同源」：表面诸元 4 邻居 —— 实据为 **§4.9 引理 1【本框架设定】**")
print("      （原标「本框架推论」**已更正**为「设定」）")
print("  ⟹ 「4」的来源是**设定**，并且**第 29 轮已经明确更正过一次定性**")
chk("T9-5", True, "「4」= 设定（且已被更正过定性）⟹ 拆分中的 a = 4 **无机制**")

# ================================================================== T9-6
hdr("T9-6  ⭐ 裁决")
print("  B5 的 0.25 =")
print("    ① 一个**被 Hawking 温度钉住的乘积**（σ = 0.25 纳特/l_P²）—— 有观测支撑；")
print("    ② 一个**不可观测的因式分解**（4 面元/单元 × 1 纳特/单元）—— 无机制；")
print("    ③ 外加一个**设定**（格距 = l_P ⟹ 每面元 l_P²）—— 无机制。")
print()
print("  ⟹ 按第 37 轮四类判定：**半拟合 / 一致性**")
print("       · 不是真预言（观测在先，且 0.25 是配进去的）")
print("       · 也不是纯公设（Hawking 温度给了它判别力：1 bit 会偏 +44.27%）")
print("  ⟹ **张力 T-9 裁决为：B5 的 0.25 = 「观测钉住的组合 + 无机制的拆分」。**")
chk("T9-6", True, "T-9 已裁决（半拟合 / 一致性；非真预言、非纯公设）")

# ================================================================== T9-7
hdr("T9-7  这条不等式 `H/N ≤ 0.25` 可证伪吗？")
print("  ⟹ **可以**：N ≤ 41 的格点会违反它（第 51 轮：N_c = 41.8）。")
print("     例如 (2,4,4) N=32 的 H/N = 0.2834 > 0.25 ⟹ **违反**。")
print("  ⚠️ 但那些是**普朗克尺度**的格点（R ≈ 1.8 l_P），没有天体物理对应；")
print("     一切真实黑洞（N ≥ 10⁷⁷）都满足，且余量 ~10⁵⁰ ⟹ **实际上不可证伪**。")
chk("T9-7", True, "形式上可证伪（N ≤ 41 违反），但**实际上没有可及的检验对象** ⟹ 弱")

# ================================================================== T9-8
hdr("T9-8  裁决后，论文该怎么说？")
print("  建议的三句话（待 S4 写入 §4.8）：")
print("   (1) 「每 4l_P² 的熵 = 1 纳特」由 **Hawking 温度**判别（1 bit 会偏 +44.27%）⟹ 是**观测定标**，不是设定；")
print("   (2) 把它拆成「4 面元/单元 × 1 纳特/单元」是**不可观测的因式分解**（观测只钉住比值）；")
print("   (3) 于是 B5 与衬底之间**不存在等式**，只有自洽性不等式 `H/N ≤ 0.25`，")
print("       而真实黑洞的余量 ≈ 10⁵⁰ ⟹ 该不等式**不构成对衬底的有效约束**。")
chk("T9-8", True, "表述建议已列出")

print()
print("=" * 78)
print("汇总：通过 {} 项，失败 {} 项".format(OK[0], FAIL[0]))
