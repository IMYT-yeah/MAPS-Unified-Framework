def check(name, lam, mu, N, decomp, note):
    """decomp: list of (盘, 重数). 验证 Σ dim(ν)·mult = dim(λ)·dim(μ)"""
    dl, dm = dim_SU(lam, N), dim_SU(mu, N)
    lhs = dl * dm
    rhs = sum(dim_SU(s, N) * m for s, m in decomp)
    has_trivial = any(len(s) == 0 or dim_SU(s, N) == 1 for s, _ in decomp)
    ok = (lhs == rhs)
    terms = " ⊕ ".join(f"{''.join(map(str, s)) if s else '1'}({dim_SU(s,N)}维)×{m}" for s, m in decomp)
    print(f"  {name}: {lhs} = {terms}  ⟹ dim 守恒 {'✓' if ok else '✗'}"
          f" | 含平凡 {'✓' if has_trivial else '—'}")
    return ok, has_trivial

