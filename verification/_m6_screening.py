# ================= Young 盘维度（SU(N)，hook length） =================

def dim_SU(lam, N):
    if not lam:
        return 1
    lam = list(lam)
    col_h = [0] * lam[0]
    for r in range(len(lam)):
        for c in range(lam[r]):
            col_h[c] += 1
    num = den = 1
    for r in range(len(lam)):
        for c in range(lam[r]):
            num *= (N + c - r)
            hook = (lam[r] - c - 1) + (col_h[c] - r - 1) + 1
            den *= hook
    return num // den

