def rd(p): return io.open(p, encoding='utf-8').read()
def wr(p, t): io.open(p, 'w', encoding='utf-8').write(t)

def sub_once(path, old, new, tag):
    t = rd(path)
    n = t.count(old)
    if n != 1:
        print('  [XX] %-24s 命中 %d 次 —— 拒绝' % (tag, n)); return
    wr(path, t.replace(old, new, 1))
    print('  [OK] %-24s 已改' % tag)

def ins_after(path, marker, block, tag, skip_if=None):
    t = rd(path)
    if skip_if and skip_if in t:
        print('  [SKIP] %-24s（已存在）' % tag); return
    L = t.split('\n')
    idx = [k for k, s in enumerate(L) if marker in s]
    if len(idx) != 1:
        print('  [XX] %-24s 命中 %d 次 —— 拒绝' % (tag, len(idx))); return
    L[idx[0] + 1:idx[0] + 1] = block
    wr(path, '\n'.join(L))
    print('  [OK] %-24s 已插入 %d 行（@L%d）' % (tag, len(block), idx[0] + 2))

