print("    紧致 U(1) 格点规范作用量: S = -β Σ_p cos(θ_p), θ_p = plaquette 相位和 = F_μν 格点版")
# cos 展开数值
theta = np.linspace(-0.5, 0.5, 100)
cos_series = 1 - theta**2/2 + theta**4/24   # 展开到 θ⁴
err = np.max(np.abs(np.cos(theta) - cos_series))
print(f"    cos θ = 1 - θ²/2 + θ⁴/24 + ... (θ≤0.5 展开误差 {err:.2e})")
print(f"    S ≈ -β Σ_p (1 - θ_p²/2) = const + (β/2)Σ_p θ_p²")
print(f"    θ_p² ~ F_μν² (格点场强) ⟹ S_eff = ∫ (1/4g²) F_μν² dx⁴ = 麦克斯韦 ✓")
print("    ⟹ 定理 B (解析严格): 紧致 U(1) 格点规范在弱场极限 = 麦克斯韦 (光子 ω=|k|)")
