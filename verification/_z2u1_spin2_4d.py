print("\n[A] 群嵌入定理: Z₂ ⊂ U(1) 作为离散子群 (代数层严格)")
print("    Z₂ = {1, -1} ⊂ U(1) = {e^{iθ}}:")
z2 = [1.0, -1.0]
closed = all((a*b in z2) for a in z2 for b in z2)
print(f"    ① 乘法封闭: {closed} (Z₂ 乘法表在 U(1) 内封闭) ✓")
