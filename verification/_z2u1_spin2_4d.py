print(f"    {'k_格点':<8}{'ω_格点':<10}{'|k|':<8}{'ω/|k|':<8}")
for ki, wi, ka in zip(k, w_k, k_abs):
    print(f"    {ki:<8.2f}{wi:<10.4f}{ka:<8.3f}{wi/ka:<8.4f}")
print("    ⟹ 长波 (k<0.5): ω/|k| ≈ 1 (光速 c=1) ✓; 短波: 格点修正 (sin 色散)")
print("    ⟹ 定理 C (数值验证): 库仑相光子 ω=|k| 长波线性色散, 横极化 2 自由度")

