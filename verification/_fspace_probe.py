# -*- coding: utf-8 -*-
"""
f_space（空间活跃度）的第一性定义：机制 B 到底有没有预言力？（2026-09-17）
==========================================================================
原文（批05 §2.3 / §3.2）：
    暗物质 = ε × 原始涨落密度 × **空间活跃度 f_space** ≈ 10⁻²⁶ kg/m³
    「在真空地带 f_space≈1，这正好与观测到的暗物质密度吻合」
    「f_space 正是『真空地带活跃度高、物质区域低』的定量化」

FS-1  ⟨f_space⟩ 被观测**唯一确定**为多少？（不是可调参数）
FS-2  朴素读法（体积分数）⟹ 需空洞占比多少？与实测比
FS-3  换读法（速率抑制因子）⟹ 还剩下预言力吗？
FS-4  扫描框架已知的无量纲量，看有没有自然给出该值的（预期全部落空）
"""
import math

c = 299792458.0
G = 6.67430e-11
hbar = 1.054571817e-34
lP = math.sqrt(hbar * G / c ** 3)
Mpc = 3.0856775814913673e22
H0 = 67.66 * 1e3 / Mpc

mP = math.sqrt(hbar * c / G)
rhoP = mP / lP ** 3
rho_crit = 3 * H0 ** 2 / (8 * math.pi * G)
RH = c / H0
N = (RH / lP) ** 2
eps_eff = 1.0 / N
eps0, beta = 7.7e-20, 0.615
OM_b, OM_cdm, OM_L, OM_m = 0.0493, 0.2618, 0.6889, 0.3111
rho_DM_obs = OM_cdm * rho_crit


def line(t):
    print("\n" + "=" * 74)
    print(t)
    print("=" * 74)


# ---------------------------------------------------------------- FS-1
line("FS-1  ⟨f_space⟩ 被观测唯一确定（它是被解出来的，不是自由参数）")
rho_bare = eps_eff * rhoP
f_needed = rho_DM_obs / rho_bare
print("  ρ_raw = ρ_P = %.6g kg/m³" % rhoP)
print("  ε_eff = 1/N = %.6g" % eps_eff)
print("  ρ_bare = ε_eff·ρ_P = %.6g kg/m³" % rho_bare)
print("  ρ_DM(观测)        = %.6g kg/m³" % rho_DM_obs)
print("  ⟹ **⟨f_space⟩ = ρ_DM/ρ_bare = %.10f = 1/%.4f**（被唯一确定）"
      % (f_needed, 1 / f_needed))
print("  ⟹ 所以机制 B 的全部内容 = 「算出一个平均值恰为 %.5f 的 f_space 场」" % f_needed)

# ---------------------------------------------------------------- FS-2
line("FS-2  朴素读法（f_space = 体积分数）被实测否证 ~20 倍")
print("  若 f_space 是『体积中处于活跃（真空）态的比例』，空洞区 f_space≈1、墙区≈0")
print("  ⟹ ⟨f_space⟩ ≈ 空洞体积分数")
print()
print("  实测（SDSS 类巡天，量级参考）：")
for name, v in (("R > 10 h⁻¹Mpc 空洞", 0.62), ("含较小空洞", 0.75),
                ("上限估计", 0.80), ("下限估计", 0.50)):
    print("    %-22s %.2f   ⟹ 需 f_space = %.2f，实际需 %.5f，**差 %.1f 倍**"
          % (name, v, v, f_needed, v / f_needed))
print()
print("  ⟹ 空洞占体积 ~50–80%%，而不是 %.1f%%。" % (100 * f_needed))
print("  ⟹ **朴素体积读法被否证 16–26 倍。** f_space 不可能是体积分数。")

# ---------------------------------------------------------------- FS-3
line("FS-3  换读法（速率抑制因子）：预言力还剩多少？")
print("  改读：f_space = (区域刷新率)/(裸刷新率) ∈ [0,1]，空洞处 = 1")
print("  则 ⟨f_space⟩ = ∫ f_space(ρ_m) dV / V，需要**抑制律** f_space(ρ_m) 才能算")
print("  可选律（都自洽）：")
for name, expr in (("指数抑制", "exp(−ρ_m/ρ_c)"),
                   ("幂律抑制", "(ρ_c/ρ_m)^p"),
                   ("阈值抑制", "θ(ρ_m < ρ_c)"),
                   ("线性抑制", "max(0, 1−ρ_m/ρ_c)")):
    print("    %-8s f_space = %s" % (name, expr))
print("  ⟹ 四种律给出**四个不同的 ⟨f_space⟩**，都能靠调 ρ_c 或 p 凑到 1/32。")
print("  ⟹ **机制 B 的预言力 = 0**：f_space 是一个自由函数，")
print("     给定任意目标 Ω_dm 都能反解出对应的 f_space。**它是拟合，不是预言。**")

# ---------------------------------------------------------------- FS-4
line("FS-4  框架已知的无量纲量里，有没有自然给出 1/32 的？")
h_tP = H0 * lP / c
cands = [
    ("1/32（目标）", 1 / 32),
    ("1/N = (H t_P)²", eps_eff),
    ("H t_P = l_P/R_H", h_tP),
    ("ε₀", eps0),
    ("β", beta),
    ("β²", beta ** 2),
    ("ε₀^(1/β)", eps0 ** (1 / beta)),
    ("2/3（跨枝保留）", 2 / 3),
    ("1/3（跨枝转移）", 1 / 3),
    ("(1/2)^5", 0.5 ** 5),
    ("(1/3)^3", (1 / 3) ** 3),
    ("3/(8π)", 3 / (8 * math.pi)),
    ("Ω_dm/λ_micro", OM_cdm / (8 * math.pi / 3)),
]
print("  候选                        值              对 1/32 的比值")
for name, v in cands:
    print("    %-24s %-15.6g %.4g" % (name, v, v / (1 / 32)))
print()
print("  ⟹ 只有 `(1/2)^5 = 1/32` 与 `Ω_dm/λ_micro`（同义反复）对得上。")
print("     框架里**没有任何已知量**自然给出 32 或 1/32。")
print("  ⚠️ (1/2)⁵ 只是恒等式（1/32 ≡ 2⁻⁵），不是机制；勿当作发现。")

line("判决")
print("""  ❌ **机制 B（ε·ρ_raw·f_space）不是预言，是拟合。**
     · ⟨f_space⟩ 被观测唯一确定为 **1/32**（不是自由参数，是解出来的）
     · 朴素体积读法 ⟹ 需空洞占 3.1%% 体积，实测 50–80% ⟹ **被否证 16–26 倍**
     · 速率抑制读法 ⟹ 需先给抑制律；四种自洽律给四个不同答案，都能凑出 1/32
     · 框架已知的无量纲量里**没有一个**自然给出 32（(1/2)⁵ 只是恒等式）

  ⟹ **结论：f_space 目前没有第一性定义，而且这个机制结构上无法被检验**——
     除非独立给出 f_space(ρ_m) 的抑制律（且该律不含可调参数）。
  ⟹ 建议：把机制 B 从"候选机制"降为"拟合式"，在论文中明确标注其零预言力；
     暗物质的定量解释仍为空白。
""")
