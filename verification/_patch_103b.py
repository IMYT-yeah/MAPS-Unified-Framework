def replace_line_by_prefix(path, prefix, transform, tag, note=""):
    t = io.open(path, encoding="utf-8").read()
    L = t.split("\n")
    cand = [i for i, s in enumerate(L) if s.startswith(prefix)]
    if len(cand) != 1:
        BAD.append("{}（行首命中 {}）".format(tag, len(cand)))
        print("  [XX] {:<26} 行首命中 {} 次 —— 拒绝".format(tag, len(cand)))
        return
    i = cand[0]
    old = L[i]
    new = transform(old)
    L[i:i + 1] = new.split("\n")
    io.open(path, "w", encoding="utf-8").write("\n".join(L))
    OK.append(tag)
    print("  [OK] {:<26} {}".format(tag, note))


def insert_before_line(path, prefix, block, tag):
    t = io.open(path, encoding="utf-8").read()
    L = t.split("\n")
    cand = [i for i, s in enumerate(L) if s.startswith(prefix)]
    if len(cand) != 1:
        BAD.append("{}（行首命中 {}）".format(tag, len(cand)))
        print("  [XX] {:<26} 行首命中 {} 次 —— 拒绝".format(tag, len(cand)))
        return
    i = cand[0]
    L = L[:i] + [block, ""] + L[i:]
    io.open(path, "w", encoding="utf-8").write("\n".join(L))
    OK.append(tag)
    print("  [OK] {:<26}".format(tag))


