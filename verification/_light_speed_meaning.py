import math as m

FAILS = []


def chk(tag, got, want, rtol=1e-9):
    ok = abs(got - want) <= rtol * max(abs(want), 1e-300)
    print("  [%s] %-42s got=%.12g   want=%.12g" % ("OK" if ok else "XX", tag, got, want))
    if not ok:
        FAILS.append(tag)


def line(t):
    print("\n" + "-" * 74)
    print(t)
    print("-" * 74)


def show(tag, val, unit=""):
    print("  %-44s %-22.10g %s" % (tag, val, unit))


# ------------------------------------------------------------------ 常数
c = 2.99792458e8
G = 6.67430e-11
h_planck = 6.62607015e-34            # 精确定义值
# 由 h 精确反算 hbar，避免硬编码 1.054571817e-34 带来的 h/hbar ≠ 2π（相对 6e-10）不一致
hbar = h_planck / (2.0 * m.pi)
lP = m.sqrt(hbar * G / c ** 3)
tP = lP / c
mPl = m.sqrt(hbar * c / G)
m_e = 9.1093837015e-31
m_p = 1.67262192369e-27
m_t = 172.76e9 * 1.602176634e-19 / c ** 2      # top quark (172.76 GeV/c^2)

