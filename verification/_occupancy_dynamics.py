# -*- coding: utf-8 -*-
"""
OD 系列 —— 衬底占位动力学：C-4 的化解，与「湮灭 = 再生」如何被 c 锁定
背景（第 18/19 轮留下的两条）：
  C-1  c 的普适性 ⟹ 衬底占位率 f = 1（此前是**假设**）
  C-4  底层四状态含「真空」，与 f = 1 冲突 ⟹ 待化解
本轮问：占位率 f 的**动力学**是什么？三种候选各自给什么 f？哪个与 c = l_P/t_P 相容？
只用标准库 math。运行：
  [TOOLCHAIN]/binaries/python/versions/3.13.12/python.exe outputs/_occupancy_dynamics.py
"""
import math as m

FAILS = []


def chk(tag, got, want, rtol=1e-9):
    ok = abs(got - want) <= rtol * max(abs(want), 1e-300)
    print("  [%s] %-44s got=%.12g   want=%.12g" % ("OK" if ok else "XX", tag, got, want))
    if not ok:
        FAILS.append(tag)


def line(t):
    print("\n" + "-" * 74)
    print(t)
    print("-" * 74)


def show(tag, val, unit=""):
    print("  %-44s %-22.10g %s" % (tag, val, unit))


# ------------------------------------------------------------------ 常数
c = 2.99792458e8
G = 6.67430e-11
h_planck = 6.62607015e-34
hbar = h_planck / (2.0 * m.pi)
lP = m.sqrt(hbar * G / c ** 3)
tP = lP / c
nu = 1.0 / tP                       # A1：湮灭-再生频率 ν ~ 1/t_P

line("OD-1  三种占位动力学及其稳态")
print("""
  设 f = 衬底格点的占位率（诸元数/格点数），τ = νt 为无量纲时间。""")


def f_paired(f0, tau):
    """(a) 配对：湮灭 = 再生（诸元数守恒，手递手）⟹ df/dtau = 0"""
    return f0


def f_poisson(f0, tau):
    """(b) 独立泊松：湮灭率 = 再生率 = ν，允许「从真空创生」⟹ df/dtau = 1 - 2f"""
    return 0.5 + (f0 - 0.5) * m.exp(-2 * tau)


def f_decay(f0, tau):
    """(c) 单向湮灭（无再生）⟹ df/dtau = -f"""
    return f0 * m.exp(-tau)


print("     tau          (a) 配对        (b) 独立泊松      (c) 单向湮灭")
print("                  f0=1.0          f0=1.0 → ?       f0=1.0 → ?")
for tau in (0.0, 0.5, 1.0, 2.0, 5.0, 20.0):
    print("     %-12.1f %.12f   %.12f   %.12f"
          % (tau, f_paired(1.0, tau), f_poisson(1.0, tau), f_decay(1.0, tau)))
print("""
  不同初值（检验 (b) 的吸引子性质）：""")
for f0 in (0.9, 0.5, 0.2, 0.01):
    print("     f0 = %-6.2f ⟹ tau=20 时 (b) f = %.12f" % (f0, f_poisson(f0, 20.0)))
chk("(a) 配对：f 守恒", f_paired(1.0, 100.0), 1.0, 1e-15)
chk("(b) 独立泊松稳态 = 1/2", f_poisson(0.9, 50.0), 0.5, 1e-12)
print("  [%s] (c) 单向湮灭：f(tau=50) = %.3g（→ 0）" % ("OK" if f_decay(1.0,50.0) < 1e-15 else "XX", f_decay(1.0,50.0)))

line("OD-2  各稳态对应的有效光速 c_eff = d/t_P，d = l_P·f^(-1/3)")
print("""
  手递手的一步 = 最近邻间距 d = l_P·f^{-1/3}（三维）或 l_P/f（沿射线）⟹ c_eff = d/t_P。""")
print("     动力学               f*        c_eff/c (3D)     Δc/c         判决")
for nm, f in (("(a) 配对，f0=1", 1.0), ("(b) 独立泊松", 0.5), ("(c) 单向湮灭", 1e-6)):
    c3 = f ** (-1.0 / 3.0)
    print("     %-20s %-10.6g %-16.10f %-12.4g %s"
          % (nm, f, c3, c3 - 1.0, "✓ 与 c 相容" if abs(c3 - 1) < 1e-12 else "✗ 被排除"))
chk("f = 1 时 c_eff = c 精确", 1.0 ** (-1 / 3.0) * lP / tP, c, 1e-15)
show("f = 1/2 时的 c_eff/c（3D）", 0.5 ** (-1.0 / 3.0))
show("f = 1/2 时的 c_eff/c（沿射线）", 1.0 / 0.5)
print("""
  ⟹ **C-1 由此从「假设」变成「后果」**：只有配对动力学（诸元数守恒）且 f₀ = 1 才给 c = l_P/t_P。
    独立泊松给 f* = 1/2 ⟹ c_eff = 2^{1/3} c = 1.2599 c（Δc/c = 26%）——**被排除**。
  ⟹ 也就是说：**c 的实测值本身就在告诉你：湮灭与再生必须是同一个事件（配对），
     不能是两个独立的泊松过程。**""")

line("OD-3  ⚠️ 你说的「每步 1/2」落在哪种动力学上？")
print("""
  你提过：若越过一个诸元的概率有 1/2，无数个 1/2 叠加 ⟹ 永远无法超光速。
  现在可以精确回答这个 1/2 是什么：""")
h_poisson = 1 - 0.5                  # 独立泊松下的空位率
h_paired = 1 - 1.0                   # 配对下的空位率
print("     · 独立泊松动力学的空位率 = 1 − f* = **%.1f** ← 正是你说的 1/2" % h_poisson)
print("     ·   ⟹ 每步跨越概率 p = %.1f，N 步后 T = (1/2)^N → 0（指数小，非零）" % h_poisson)
print("     · 配对动力学的空位率 = 1 − f = **%.1f**" % h_paired)
print("     ·   ⟹ 每步跨越概率 p = 0 ⟹ T = 0 对任何 N ≥ 1（**恒为零**）")
for N in (1, 2, 10, 100):
    print("         N=%-5d (1/2)^N = %.6g ；0^N = 0" % (N, 0.5 ** N))
print("""
  ⟹ **两种动力学都禁止超光速，但机制完全不同**：
     独立泊松：p = 1/2，T = 2^{-N} —— 指数小但非零（你的直觉完全正确）；
     配对（框架取这个）：p = 0，T = 0 —— 不是小，是恒为零。
  ⟹ 而且**独立泊松这个"1/2 模型"被 c 排除了**（Δc/c = 26%），所以框架实际处在
     比你的设想**更强**的那一边：连一个 1/2 的机会都没有。""")

line("OD-4  C-4 化解：真空态的测度")
print("""
  第 19 轮的四状态枚举 {正, 负, 湮灭中, 真空} 里，「真空」分支的测度 = 空位率 h：""")
print("     动力学            h = 1 − f        真空态测度     是否与 4 bits 计数冲突")
for nm, f in (("配对（f0=1）", 1.0), ("独立泊松", 0.5)):
    h = 1 - f
    print("     %-16s %-16.6g %-14.6g %s"
          % (nm, h, h, "否（真空为零测度，仅作逻辑态）" if h == 0 else "冲突（c 偏 %.0f%%）" % (100 * (f ** (-1 / 3) - 1))))
print("""
  ⟹ **C-4 的解**：「真空」是**逻辑态**（枚举需要它来凑出 16 = 4×4 ⟹ 4 bits），
     但在真实动力学中**测度为零**——因为格点就是由诸元构成的：
     **无诸元 ⟹ 无格点（空间本身）**，不是"格点是空的"。
  ⟹ 这与框架本体论一致（空间由风暴生成），也让 C-1 不再是外加假设。""")

line("OD-5  ⚠️ 顺带修正：论文 §4 的 k = 2^{1/4} 与修正后的 B5 不自洽")
print("""
  论文 §4 有「k = 2^{1/4} 微态计数」的说法，第 19 轮得出了底层 16 原始态。二者对账：""")
k_old = 2 ** 0.25
k_new = m.exp(0.25)
show("k_old = 2^{1/4}", k_old)
show("⟹ 每格点熵 ln k_old (nats)", m.log(k_old))
show("⟹ 每格点熵 log2 k_old (bits)", m.log2(k_old))
chk("k_old 对应 1/4 bit/面元", m.log2(k_old), 0.25, 1e-15)
show("B5 修正后目标：每格点 0.25 nat", 0.25)
show("⟹ 应为 k_new = e^{1/4}", k_new)
chk("k_new 对应 0.25 nat/面元", m.log(k_new), 0.25, 1e-15)
show("k_new / k_old", k_new / k_old)
show("两者熵之比 = 1/ln2", (m.log(k_new)) / (m.log(k_old)))
chk("比值 = 1/ln2", m.log(k_new) / m.log(k_old), 1 / m.log(2), 1e-12)
print("""
  ⟹ **论文 §4 的 k = 2^{1/4} 与 B5 原来的「1/4 bit/面元」是同一件事的两种写法**——
     两者都缺同一个 ln2。第 15/19 轮只修了 B5（1 nat/块），**§4 的 k 没跟着改**，
     现在自相矛盾。⟹ **k 应改为 e^{1/4} = %.6f**（对应 0.25 nat/面元）。""" % k_new)

line("OD-6  判决")
print("""
  ✅ **C-1 由假设变后果**：占位动力学只有「配对（湮灭=再生，诸元数守恒）且 f₀=1」
     才给 c = l_P/t_P。独立泊松给 f* = 1/2 ⟹ c_eff = 1.2599 c（Δc/c = 26%）⟹ 排除。
     ⟹ **c 的实测值在告诉你：湮灭与再生必须是同一事件。**
  ✅ **C-4 化解**：「真空」是逻辑态（枚举需要它凑出 16 = 4×4），动力学测度为零
     —— 无诸元 ⟹ 无格点 ⟹ 不是"空格点"。与框架本体论（空间由风暴生成）一致。
  ✅ **你那个「1/2」落到实地了**：它正是「独立泊松」衬底的空位率。
     该模型下 T = 2^{-N}（指数小、非零）——你的直觉精确成立；
     但它被 Δc/c = 26% 排除 ⟹ 框架实际取的是更强的 p = 0（恒为零）。
  ⚠️ **新发现的一致性缺口**：论文 §4 的 k = 2^{1/4}（= 1/4 bit/面元）与第 19 轮
     修正后的 B5（0.25 nat/面元）差同一个 ln2 ⟹ **k 应改为 e^{1/4} = 1.2840**。
  ❗ 仍未解决：为何 f₀ = 1（初值问题）；以及 16 原始态 → 1.284 有效态的压缩 11.09 的自然性。""")

line("汇总")
print("  失败项：%s" % ((", ".join(FAILS)) if FAILS else "无"))
print("  关键数：f*=1（配对）｜f*=1/2（泊松）⟹ Δc/c=26%%｜k: 2^{1/4}=%.6f → e^{1/4}=%.6f"
      % (k_old, k_new))
