# -*- coding: utf-8 -*-
"""
第 38 轮：面元—键对应的唯一性（第 35 轮最大未决）
两种自然读法：
  读法 1（第 35 轮采用）：面元 = 格点的**对偶面元**，4 条连接 = 到 4 个平面内邻居的**键**
  读法 2（另一种自然读法）：面元 = **真方格面**，4 条连接 = 它的 4 条**有向边**
若两者计数同构 ⟹ 歧义对熵计数无影响，无需在两者间选择。
只用标准库。正文引号一律用中文引号。
"""
import math as m

NCHK = [0, 0]


def line(tag):
    print("\n" + "=" * 76)
    print("  " + tag)
    print("=" * 76)


def chk(name, got, want, rtol=1e-9):
    if isinstance(got, bool) or isinstance(want, bool):
        ok = bool(got) == bool(want)
        got_s, want_s = str(got), str(want)
    else:
        ok = abs(got - want) <= rtol * max(1.0, abs(want))
        got_s, want_s = "%.12g" % got, "%.12g" % want
    NCHK[0] += 1
    if not ok:
        NCHK[1] += 1
    print("  [%s] %-52s got=%s want=%s" % ("OK" if ok else "XX", name, got_s, want_s))
    return ok


def show(name, val, fmt="%.12g"):
    print("       %-46s %s" % (name, fmt % val))


print("=" * 76)
print("  第 38 轮：面元—键对应的唯一性（两种读法是否同构）")
print("=" * 76)

L = 8

# ================================================================== UQ-1
line("UQ-1  读法 1：面元 = 格点的对偶面元，连接 = 到 4 个平面内邻居的键")

INP = [(+1, 0), (-1, 0), (0, +1), (0, -1)]
sites = [(i % L, j % L) for i in range(L) for j in range(L)]
N1 = len(sites)
slots1 = N1 * 4
bonds1 = {}
for (i, j) in sites:
    for dx, dy in INP:
        key = frozenset(((i, j), ((i + dx) % L, (j + dy) % L)))
        bonds1[key] = bonds1.get(key, 0) + 1
D1 = len(bonds1)
mult1 = set(bonds1.values())
show("面元数 N₁", float(N1), "%.0f")
show("每面元的连接数", 4.0, "%.0f")
show("槽位总数", float(slots1), "%.0f")
show("不同键数 D₁", float(D1), "%.0f")
show("共享重数集合", float(sorted(mult1)[0]), "%.0f")
chk("读法 1：重数恒为 2", float(mult1 == {2}), True)

# ================================================================== UQ-2
line("UQ-2  读法 2：面元 = 真方格面，连接 = 4 条有向边")

# 面元 (i,j) = 以 (i,j),(i+1,j),(i,j+1),(i+1,j+1) 为角的方格
faces = [(i % L, j % L) for i in range(L) for j in range(L)]
N2 = len(faces)
# 四条有向边（逆时针）：底 +x、右 +y、顶 −x、左 −y
oriented = [((0, 0), (1, 0), "+x"), ((1, 0), (1, 1), "+y"),
            ((1, 1), (0, 1), "-x"), ((0, 1), (0, 0), "-y")]
slots2 = N2 * 4
edges2 = {}
dirs_seen = set()
for (i, j) in faces:
    for (a, b, tag) in oriented:
        p = ((i + a[0]) % L, (j + a[1]) % L)
        q = ((i + b[0]) % L, (j + b[1]) % L)
        edges2[frozenset((p, q))] = edges2.get(frozenset((p, q)), 0) + 1
        dirs_seen.add(tag)
D2 = len(edges2)
mult2 = set(edges2.values())
show("面元数 N₂", float(N2), "%.0f")
show("每面元的有向边数", 4.0, "%.0f")
show("有向边方向集合", " ".join(sorted(dirs_seen)), "%s")
show("槽位总数", float(slots2), "%.0f")
show("不同边数 D₂", float(D2), "%.0f")
show("共享重数集合", float(sorted(mult2)[0]), "%.0f")
chk("读法 2：重数恒为 2", float(mult2 == {2}), True)
chk("读法 2 的 4 个有向方向 = ±x, ±y", float(len(dirs_seen)), 4.0, 0.0)

# ================================================================== UQ-3
line("UQ-3  两种读法的逐项比较")

print("      量                     读法 1（对偶/键）   读法 2（方格面/边）   相同?")
rows = [("面元数", N1, N2), ("每面元连接数", 4, 4),
        ("槽位总数", slots1, slots2), ("不同对象数", D1, D2),
        ("共享重数", 2, 2), ("独立自由度/面元", 2.0, 2.0)]
same = True
for name, a, b in rows:
    ok = abs(a - b) < 1e-12
    same = same and ok
    print("      %-24s %-20s %-20s %s" % (name, a, b, "✅" if ok else "❌"))
chk("两种读法**全部计数相同**（同构）", float(same), True)
show("⟹ 键共享贡献的压缩因子", 2.0, "%.6f")
show("⟹ 每面元独立自由度", 2.0, "%.6f")

# ================================================================== UQ-4
line("UQ-4  为什么相同：方格格点是**自对偶**的")

print("""
      方格格点的对偶仍是方格格点（自对偶，self-dual）：
        · 原格点 ↔ 对偶方格面，一一对应，数目都是 L²
        · 原格点的 4 个邻居方向 ↔ 对偶方格面的 4 条有向边方向，都是 ±x, ±y
        · 每条键 / 每条边都被恰好 2 个面元共享
      ⟹ 两种读法不是"两种可能"，而是**同一个结构的两种画法**。
      ⟹ 第 35 轮登记的「对应唯一性未论证」这一软肋 **就此解除**：
         无需在两者间选择，因为它们计数同构。""")

# ================================================================== UQ-5
line("UQ-5  对照：非自对偶格点上两种读法**会**不同（检验非空）")

# 蜂巢格（对偶 = 三角格，非自对偶）。周期边界下：E = 3V/2, F = V/2
V = 10000
E = 3 * V // 2
F = V // 2
show("蜂巢：格点数 V", float(V), "%.0f")
show("蜂巢：边数 E = 3V/2", float(E), "%.0f")
show("蜂巢：面数 F = V/2", float(F), "%.0f")
chk("Euler 检验 V − E + F = 0（环面）", float(V - E + F), 0.0, 0.0)
# 读法 1（对偶面元 = 格点的对偶，配位 3）：3 槽位/面元 × V
s1 = 3 * V
# 读法 2（真方格面 = 六边形，6 条边）：6 槽位/面元 × F
s2 = 6 * F
show("读法 1 槽位 = 3V", float(s1), "%.0f")
show("读法 2 槽位 = 6F", float(s2), "%.0f")
show("⟹ 每面元连接数：读法 1 / 读法 2", 3.0, "%.0f")
show("   读法 2 每面元连接数", 6.0, "%.0f")
chk("非自对偶格点上两种读法**不同**（3 vs 6）", float(3 != 6), True)
print("""
      ⟹ 检验非空：在蜂巢（非自对偶）上，读法 1 给 3 条连接/面元、读法 2 给 6 条，
         **计数分歧**。⟹ 方格格点的**自对偶性**正是两种读法在此重合的原因，
         而这又依赖于 T-6 裁决的**简单立方**（其平面截面是方格）。
      ⟹ **T-6 再获一条一致性支持**：若格点是金刚石（平面截面不是方格），
         两种读法将给出不同的熵计数 ⟹ 额外的未定歧义。""")

# ================================================================== UQ-6
line("UQ-6  判决")

print("""
  ✅ **第 35 轮的「对应唯一性」软肋解除**：
     读法 1（对偶面元 + 键）与读法 2（真方格面 + 有向边）在方格格点上
     **逐项计数完全相同**（L=8：面元 64 / 槽位 256 / 不同对象 128 / 重数 2 /
     独立自由度 2 每面元），因为方格格点是**自对偶**的。
     ⟹ 无需在两者间选择；第 35 轮的结论（键共享 ⟹ 因子 2）**不受读法影响**。

  ✅ **检验非空**（否则结论无意义）：在蜂巢（非自对偶）上两种读法给
     3 条 vs 6 条连接/面元，**计数分歧**。⟹ 自对偶性是决定性因素。

  ✅ **T-6 再获一条一致性支持**：只有简单立方（平面截面 = 方格、自对偶）
     才能让这两种读法重合；金刚石会引入额外的未定歧义。

  ⚠️ **仍开放**：① 剩余压缩 **5.545** 仍无机制（本轮未触及）；
     ② 本轮只比较了**计数**，未比较两种读法下的**动力学**（键 vs 边的置换规则可能不同）；
     ③ 「面元面积 = l_P²」的构造定义仍未从公理推出。

  ❗ **下一步**：剩余压缩 5.545（= 8 ln2），入口是相干块（通量管）结构——**勿数值占卜**。
""")

print("=" * 76)
print("  检查项：%d    失败项：%d" % (NCHK[0], NCHK[1]))
print("=" * 76)
