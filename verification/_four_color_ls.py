import math as m
import random

CHECKS = []
def chk(name, got, want, tol):
    ok = abs(got - want) <= tol * max(1.0, abs(want))
    CHECKS.append((name, ok))
    print("  [%s] %-60s got=%.10g  want=%.10g" % ("OK" if ok else "XX", name, got, want))
    return ok

def show(name, val):
    print("        %-60s = %.10g" % (name, val))

def line(t):
    print("\n" + "=" * 82)
    print(t)
    print("=" * 82)

