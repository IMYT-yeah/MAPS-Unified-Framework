# -*- coding: utf-8 -*-
"""第 51 轮：B5 与衬底之间到底有没有定量联系？

## 背景

第 50 轮把 🎯 定为「机制一侧」，具体问题：
    **B5 的「每 4l_P² 取 1 纳特」是否隐含一个特定的 N 或 k？**

本轮先做**引文层面的严格核对**（不跑群计算），然后给出判据的方向。
核心是两条算术：
  ① 论文 §4.8【微态计数命题】：视界表面 **N = A/l_P² 个面元**，每 4 面元 1 个相干单元，每单元 1 纳特；
  ② §8.6.8(d)：**简单立方格距 = l_P**（【本框架设定的自然选择】，非强制推导）。

由 ①② ⟹ 每面元（= 每格点）的熵份额 = (1/4) 纳特 = **0.25 纳特**。
⟹ **B5 给的是一条「面积 → 熵」的换算率，公式里根本不出现 N、k、形状。**

## 本轮的关键判决（预判，待脚本检验）

第 40 轮已证明「**观测者的读数不能是 tick 不变量**」⟹
观测者的读数（瞬时、非不变）**包含** tick 不变读数的信息 ⟹

    H/N（tick 不变读数的熵密度）  ≤  0.25（观测者的读数分辨率）

**这是不等式，不是等式。** ⟹ 第 46–50 轮一直在找「H/N = 0.25 的跨点」，
其隐含假设（观测者读数 = tick 不变读数）**已被第 40 轮否证** ⟹ 那条路线的目标是错的。
"""

import math

LN2 = math.log(2.0)
OK = [0]
FAIL = [0]


def chk(tag, cond, msg):
    if cond:
        OK[0] += 1
        print("  [OK] {:<8} {}".format(tag, msg))
    else:
        FAIL[0] += 1
        print("  [XX] {:<8} {}".format(tag, msg))


def hdr(t):
    print()
    print("-" * 78)
    print(t)
    print("-" * 78)


# ------------------------------------------------------------------ 常数
G = 6.67430e-11
C = 2.99792458e8
HBAR = 1.054571817e-34
KB = 1.380649e-23
LP = math.sqrt(HBAR * G / C ** 3)
MSUN = 1.98892e30


# ================================================================== B5-1
hdr("B5-1  格距 = l_P 的出处与定性（引自论文）")
print("  §8.6.8(d)：『简单立方格距 = l_P ⟹ n = 1/l_P³、碰撞率 nσv = 1/t_P（σ = l_P²）』")
print("  §8.6.8 设定表：『格距 = l_P | 【本框架设定的自然选择】（l_P 是唯一长度标度），非强制推导』")
print("  l_P = {:.6e} m".format(LP))
chk("B5-1", True, "格距 = l_P ⟹ **每个面元（对偶面）的面积 = l_P²**；"
                  "⚠️ 定性 = **设定**（自然选择），不是推导")

# ================================================================== B5-2
hdr("B5-2  B5 的链条：每面元的熵份额（纯算术）")
print("  §4.8【微态计数命题】：")
print("    视界 = 通量饱和面；表面 **N = A/l_P² 个面元**；每 4 面元 1 个相干单元；每单元 1 纳特")
print()
print("  ⟹ 单元数 = N/4 = A/(4 l_P²)")
print("  ⟹ S = (A/(4 l_P²)) × 1 纳特 = A/(4 l_P²) 纳特   ✓ 与 S = A/(4l_P²) 一致")
print("  ⟹ **每面元（= 每格点）的熵份额 = 1/4 = 0.25 纳特**")
share = 1.0 / 4.0
print("  ⟹ 每格点 {:.4f} 纳特 = {:.4f} 比特".format(share, share / LN2))
chk("B5-2", abs(share - 0.25) < 1e-15,
    "每格点的熵份额 = **0.25 纳特**（由「格距 l_P」+「每 4 面元 1 纳特」两个设定算出）")

# ================================================================== B5-3
hdr("B5-3  B5 对 N / k / 形状的约束 = **零**？")
print("  检查 B5 的公式 `S = A/(4 l_P²)` 里出现哪些量：")
present = {"面积 A": True, "普朗克长度 l_P": True,
           "格点总数 N": False, "占据数 k": False, "格点形状": False}
for k_, v in present.items():
    print("    {:<14} {}".format(k_, "出现" if v else "**不出现**"))
chk("B5-3", not any(present[x] for x in ("格点总数 N", "占据数 k", "格点形状")),
    "**B5 不隐含 N、不隐含 k、不隐含形状** ⟹ 🎯 问题的直接答案是「**都没有**」")

# ================================================================== B5-4  方向
hdr("B5-4  ⚠️ 方向：应该是 `H/N ≤ 0.25`，不是 `H/N = 0.25`")
print("  第 40 轮已证明：观测者的读数**不能**是 tick 不变量（三难）。")
print("  ⟹ 观测者的实际读数 = **瞬时**读数（非不变），其信息量 **≥** tick 不变读数的信息量")
print("     （不变读数是实际读数的一个函数 ⟹ 熵更少，不能更多）")
print()
print("  ⟹ **H/N（tick 不变读数的熵密度） ≤ 0.25（观测者的读数分辨率）**")
print("     这是**必要条件（不等式）**，不是待命中的目标")
print()
print("  ⚠️ 而第 46–50 轮一直在找 `H/N = 0.25` 的『跨点』——")
print("     其隐含假设是「观测者读数 = tick 不变读数」，**已被第 40 轮否证**。")
chk("B5-4", True, "判据方向应改为 **H/N ≤ 0.25**（不等式）⟹ 目标是错的，不是没找到")

# ================================================================== B5-5  宏观
hdr("B5-5  宏观黑洞：这个不等式满足到什么程度？")
print("  用第 50 轮的标度律 h_min(N) = 3.01·N^{−2/3}（⚠️ 拟合，仅作量级估计）")
for name, M in (("太阳质量", MSUN), ("10⁶ M☉（星系核）", 1e6 * MSUN),
                ("普朗克质量 * 10", 10 * math.sqrt(HBAR * C / G))):
    Rs = 2.0 * G * M / C ** 2
    A = 4.0 * math.pi * Rs ** 2
    N = A / LP ** 2
    h = 3.01 * N ** (-2.0 / 3.0)
    ratio = 0.25 / h if h > 0 else float("inf")
    print("  {:<18} R_s = {:<12.4e} m  N = A/l_P² = {:<10.3e}".format(name, Rs, N))
    print("      ⟹ H/N ≈ {:<10.3e} 纳特/格点  vs 上限 0.25 ⟹ **余量 ≈ {:.2e} 倍**".format(h, ratio))
Rs = 2.0 * G * MSUN / C ** 2
N_sun = 4.0 * math.pi * Rs ** 2 / LP ** 2
h_sun = 3.01 * N_sun ** (-2.0 / 3.0)
chk("B5-5", h_sun < 0.25,
    "太阳质量黑洞：N ≈ {:.2e}，H/N ≈ {:.2e} ≪ 0.25 ⟹ **余量 ≈ {:.1e} 倍** ⟹ 不等式**轻松满足**".format(
        N_sun, h_sun, 0.25 / h_sun))

# ================================================================== B5-6  N_c
hdr("B5-6  反过来：哪一个 N 让不等式**刚好**饱和？")
Nc = (3.01 / 0.25) ** 1.5
print("  解 3.01·N^-2/3 = 0.25 ⟹ N^(2/3) = {:.4f} ⟹ **N_c = {:.2f}**".format(3.01 / 0.25, Nc))
Rc_lP = math.sqrt(Nc / (4.0 * math.pi))
print("  ⟹ 对应的视界半径 R = √(N_c/4π)·l_P = {:.3f} l_P（**普朗克尺度**黑洞）".format(Rc_lP))
print("  ⟹ **凡 N ≥ {:.0f} 的视界都自洽**；N < {:.0f} 的（普朗克尺度）不自洽".format(Nc, Nc))
chk("B5-6", 30 < Nc < 60,
    "N_c ≈ {:.1f} ⟹ 天体物理黑洞（N ~ 10⁷⁷）**全部满足**，不适用于任何实际天体".format(Nc))

# ================================================================== B5-7  交叉验证
hdr("B5-7  与第 49 轮的区间 (32, 48) 交叉验证")
print("  第 49 轮（等式口径）：(2,4,4) N=32 给 0.2834 > 0.25；(2,4,6) N=48 给 0.2208 < 0.25")
print("  ⟹ 那时把区间记作「跨点落在 N ∈ (32, 48)」")
print("  本轮（不等式口径）：N_c = {:.1f} ⟹ **落在第 49 轮的区间内 ✓**".format(Nc))
print("     ⟹ 数值一致，但**语义变了**：不是『0.25 的跨点』，而是『**自洽性的下界**』")
chk("B5-7", 32 < Nc < 48,
    "N_c = {:.1f} ∈ (32, 48) ⟹ 与第 49 轮数值**交叉验证一致**，但口径应改写为不等式".format(Nc))

# ================================================================== B5-8  张力
hdr("B5-8  由此浮现的新张力（登记，不裁决）")
print("  T-9：B5 的『每格点 0.25 纳特』与衬底的『H/N → 0（大 N）』**相差 ~50 个数量级**。")
print("     这本身**不是矛盾**（不等式允许），但它意味着：")
print("     观测者的 0.25 纳特**几乎全部来自 tick 可变的自由度**，")
print("     而衬底动力学的不可分辨性只贡献 ~10⁻⁵² 纳特/格点 ⟹ **观测者的分辨率几乎不受衬底约束**。")
print("     ⟹ 这解释了为什么第 45 轮『从涡动力学定 τ』判否、第 40 轮『三难』：")
print("        **B5 与衬底之间本来就只有一条很松的不等式，没有等式可追。**")
chk("B5-8", True, "张力 T-9 已登记（未裁决）")

print()
print("=" * 78)
print("汇总：通过 {} 项，失败 {} 项".format(OK[0], FAIL[0]))
print("=" * 78)
