# -*- coding: utf-8 -*-
"""
第 37 轮：把「宇宙级开源代码 vs 逆向工程」这个比喻 sharpen 成可检验判据，并对框架自审。
核心命题：逆向工程 ⟹ 每个现象有自己的参数（自由度高、总能拟合）；
          源码级     ⟹ 少数参数被**多处复用**（过约束）⟹ 改一处坏另一处 ⟹ 可证伪。
只用标准库。正文引号一律用中文引号。
"""
import math as m

EPS0 = 7.7e-20
BETA = 0.615
NCHK = [0, 0]


def line(tag):
    print("\n" + "=" * 76)
    print("  " + tag)
    print("=" * 76)


def chk(name, got, want, rtol=1e-9):
    if isinstance(got, bool) or isinstance(want, bool):
        ok = bool(got) == bool(want)
        got_s, want_s = str(got), str(want)
    else:
        ok = abs(got - want) <= rtol * max(1.0, abs(want))
        got_s, want_s = "%.12g" % got, "%.12g" % want
    NCHK[0] += 1
    if not ok:
        NCHK[1] += 1
    print("  [%s] %-52s got=%s want=%s" % ("OK" if ok else "XX", name, got_s, want_s))
    return ok


def show(name, val, fmt="%.12g"):
    print("       %-46s %s" % (name, fmt % val))


print("=" * 76)
print("  第 37 轮：源码级 vs 逆向工程 —— 判据与自审")
print("=" * 76)

# ================================================================== SV-1
line("SV-1  判据：两者在结构上差在哪")

print("""
  | 特征 | 逆向工程（有效理论） | 源码级 |
  |---|---|---|
  | 参数 | 每现象一套，随精度增长 | **少数参数被多处复用** |
  | 自由度 | 高（总能拟合） | **过约束**（改一处坏另一处） |
  | 失败模式 | 加参数即可消化 | **无法靠微调逃脱**（敏感度锁死） |
  | 空白 | 可留给"新物理" | **必须承认**（如暗物质） |
  | 验证方式 | 拟合优度 | **先算后验的真预言** |

  ⟹ 可量化的核心指标：**复用率 = 现象数 / 参数数**。
     逆向工程 ≈ 1（一对一）；源码级 ≫ 1（一对多）。""")

# ================================================================== SV-2
line("SV-2  框架的参数账与复用账")

params = ["ε₀ (A2 泄漏幅度)", "β (A2 泄漏指数)"]
phenomena_using = {
    "A2 的 ε(E) 幂律": ["暗能量能标 E_c", "暗能量密度 Ω_Λ", "重子/光子比 η", "状态方程 w(z) 偏离"],
}
n_param = len(params)
n_phen = len(phenomena_using["A2 的 ε(E) 幂律"])
show("核心拟合参数数", float(n_param), "%.0f")
for p in params:
    print("         · %s" % p)
show("同一条机制（A2）被复用的现象数", float(n_phen), "%.0f")
for x in phenomena_using["A2 的 ε(E) 幂律"]:
    print("         · %s" % x)
reuse = n_phen / float(n_param)
show("**复用率 = 现象 / 参数**", reuse, "%.4f")
chk("复用率 > 1（源码级特征，非一对一拟合）", float(reuse > 1.0), True)
print("      ⟹ 2 个参数要同时养活 4 个现象 ⟹ **过约束 2 倍**。")

# ================================================================== SV-3
line("SV-3  过约束的后果：改一处坏另一处（源码级的可证伪性）")

# Ω_Λ 的 β 敏感度（第 21 轮已有结论，此处重算）
sens = -4.0 * m.log(EPS0) / BETA ** 2
show("d ln Ω_Λ / dβ", sens, "%.6f")
gap = 23.76                            # O-Λ：观测 / 框架
dln = m.log(gap)
dbeta = dln / sens
show("为补上 %.2f 倍所需的 Δβ" % gap, dbeta, "%.6f")
show("  相对变化 Δβ/β", dbeta / BETA * 100, "%.6f")
# E_c 的 β 敏感度：E_c = M_Pl ε₀^(1/β) ⟹ dlnE_c/dβ = -ln ε₀ / β²
sens_Ec = -m.log(EPS0) / BETA ** 2
show("d ln E_c / dβ", sens_Ec, "%.6f")
dlnEc = sens_Ec * dbeta
show("⟹ E_c 的相对变化 Δln E_c", dlnEc, "%.6f")
show("⟹ E_c 被推偏的倍数", m.exp(dlnEc), "%.6f")
print("""
      ⟹ **想靠调 β 补上 Ω_Λ 的 23.76 倍，需要 β 变 %.2f%%；
         而同一改动会把已经对上的暗能量能标 E_c 推偏 %.2f 倍。**
      ⟹ 这正是「源码级」的可证伪性：参数被复用 ⟹ 微调救不了 ⟹ 只能承认失败（O-Λ）。"""
      % (dbeta / BETA * 100, m.exp(dlnEc)))
chk("补 Ω_Λ 所需的 β 改动会显著破坏 E_c（>1.5 倍）", float(m.exp(dlnEc) > 1.5), True)

# ================================================================== SV-4
line("SV-4  反向对照：逆向工程会怎么做（ΛCDM 的参数账）")

LCDM = 6
SM = 19
show("ΛCDM 自由参数", float(LCDM), "%.0f")
show("标准模型自由参数", float(SM), "%.0f")
show("两者合计", float(LCDM + SM), "%.0f")
show("框架核心参数（A2 两个）", float(n_param), "%.0f")
print("""
      ⟹ 数量对比悬殊（2 vs 25），但**数量本身不是判据**——
        逆向工程可以只报 2 个参数而把其余藏进"初始条件 / 截断 / 选择定则"。
      ⟹ 真正的判据是**过约束**：框架目前处于
        「2 个参数要养 4 个现象，其中 Ω_Λ 未通过」的状态。
        **逆向工程永远不会处于这种状态**（它总能加参数消化掉）。""")

# ================================================================== SV-5
line("SV-5  关键自审：真预言 vs 事后解释（postdiction）")

verdicts = [
    ("Ω_K = 0（平坦性）", "已知答案后导出", "postdiction", "机制有价值，但不是预言"),
    ("E_c = 1.0181 meV", "框架原已当输入 1.01", "postdiction", "由 2 参数推出仍是进展"),
    ("ε(1 TeV) ≈ η", "1 TeV 是配出来的", "半拟合", "2% 符合但非独立预言"),
    ("EMRI 进动差 δ = 0.30·x_p", "**先算后验，未观测**", "真预言", "27σ/28σ，LISA 可判决 ★★★"),
    ("FQH ε 项（S-E5）", "**先算后验，未观测**", "真预言", "极低温强磁场平台可测 ★★★"),
    ("void-CPT-κ 异常", "**先算后验，未观测**", "真预言", "10–30 Mpc/h 尺度"),
    ("黑洞强场 B1–B5", "**先算后验，未观测**", "真预言", "10⁻⁸ 量级，极难"),
    ("Ω_Λ 差 23.76 倍", "**主动承认的失败**", "失败", "无法靠微调逃脱 ✓"),
    ("暗物质", "**完全空白**", "失败", "三机制全挂，诚实登记"),
]
n_pred = sum(1 for v in verdicts if v[2] == "真预言")
n_post = sum(1 for v in verdicts if v[2] in ("postdiction", "半拟合"))
n_fail = sum(1 for v in verdicts if v[2] == "失败")
print("      结果                              性质                        判定")
for name, kind, cls, note in verdicts:
    print("      %-34s %-28s %s" % (name, kind, cls))
show("真预言条数（先算后验、未观测）", float(n_pred), "%.0f")
show("postdiction / 半拟合条数", float(n_post), "%.0f")
show("主动承认的失败条数", float(n_fail), "%.0f")
chk("真预言 ≥ 4 条（源码级最硬的指标）", float(n_pred >= 4), True)
print("""
      ⚠️ **这是本次自审最重要的结论**：
         框架最引以为傲的结果（平坦性、暗能量能标）在严格意义上是 **postdiction**——
         答案已知才导出来的。真正区分源码级与逆向工程的，
         是那 %d 条**先算后验、尚未观测**的硬预言（EMRI / FQH / void-CPT-κ / B1–B5）。
         **它们的判决结果才是这个比喻的裁决场。**""" % n_pred)

# ================================================================== SV-6
line("SV-6  判决")

print("""
  ✅ **比喻成立，且有可检验内容**：源码级 vs 逆向工程的分水岭不是"参数少"，
     而是**参数被复用导致的过约束**。框架目前 2 参数养 4 现象（复用率 %.1f），
     并因此卡在「Ω_Λ 差 23.76 倍且**无法靠微调逃脱**」——这是源码级理论才有的处境。

  ✅ **两条最强的源码级证据**：
     ① 过约束示例：补 Ω_Λ 需 β 变 %.2f%%，而同一改动把 E_c 推偏 %.2f 倍 ⟹ 微调救不了；
     ② 真预言 %d 条（EMRI 27σ、FQH ε 项、void-CPT-κ、B1–B5），均**先算后验、尚未观测**。

  ⚠️ **必须泼的冷水（比喻的边界）**：
     ① 框架**仍有 2 个拟合参数**（ε₀, β），不是零参数——严格说还没到"纯源码"；
     ② 最亮眼的结果是 **postdiction**（答案已知），不是预言；
     ③ **暗物质完全空白**——源码级理论不能靠"加参数"消化，只能承认；
     ④ 质量谱、1 TeV 能标仍是拟合 ⟹ 距"从源码跑出整个宇宙"还很远。

  ❗ **比喻的正确用法**：把它当**研究纲领**（要求过约束、要求真预言、禁止加参数消化失败），
     不要当**已完成的主张**。目前框架是「按源码级纲领在做的理论」，不是「已验证的源码」。
""" % (reuse, dbeta / BETA * 100, m.exp(dlnEc), n_pred))

print("=" * 76)
print("  检查项：%d    失败项：%d" % (NCHK[0], NCHK[1]))
print("=" * 76)
