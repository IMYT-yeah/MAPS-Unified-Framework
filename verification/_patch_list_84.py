def sub_once(path, old, new, tag, n=1):
    t = io.open(path, encoding="utf-8").read()
    c = t.count(old)
    if c != n:
        print("  [XX] {:<42} 命中 {}（期望 {}）".format(tag, c, n))
        BAD.append(tag)
        return
    io.open(path, "w", encoding="utf-8").write(t.replace(old, new, n))
    print("  [OK] {:<42} 已改".format(tag))


def check_num(tag, strict=True):
    L = io.open(GL, encoding="utf-8").read().split("\n")
    nums = [int(m.group(1)) for m in (re.match(r"^### 1\.(\d+) ", s) for s in L) if m]
    ok = nums == list(range(1, len(nums) + 1))
    print("  [{}] {:<28} 1.{}–1.{}  连续={}  重复={}".format(
        "OK" if ok else ("XX" if strict else "INFO"), tag, nums[0], nums[-1], ok,
        [x for x in set(nums) if nums.count(x) > 1] or "无"))
    if not ok and strict:
        BAD.append("编号" + tag)
    return ok


