# -*- coding: utf-8 -*-
"""
第 45 轮核验：观测者自身的周期 τ 能否被定出？
============================================
第 40 轮留下：B5 的读数分辨率 δ 无法由衬底动力学给出；时间平均路线给
`τ = t_P/(δ²e²)`，**一个方程两个未知量** ⟹ 零预言力。
唯一入口 = **观测者自身的周期 τ**（§4.9 的 N1–N4 涡动力学）。

框架里观测者是什么（论文 §4.9）：
  O1：观测者 = **现在平面孤子**
  N1：稳态涡需**相位累积 4π 的整数倍** ⟹ 锁定旋转轴 ⟹ 至少一个平面
  N2：0 平面退化 / 2 平面冲突 / 3 平面各向同性 ⟹ 恰好一个（稳定性 0.00/1.00/0.30/0.05）
⟹ **τ = 涡走完一个相位周期的时间**。

本轮：
  ① 复算时间平均公式，给出 τ–δ 的一一对应与 **τ 的定量下界**（新判据）；
  ② 枚举 τ 的候选来源（涡旋转 / 康普顿周期），看每个引入了什么新未知量；
  ③ 检查候选 τ = 2π t_P 的**双重解释是否一致**（l_P 涡绕一圈 vs 普朗克质量的康普顿周期）；
  ④ 判决：τ 是否被唯一确定，还是"公设上移"的**无穷回归**。

检查项 OT-1 … OT-7，末尾必须打印汇总行。
"""

import math

T_P = 5.391247e-44          # s
H = 6.62607015e-34          # J·s
HBAR = 1.054571817e-34      # J·s
C = 299792458.0             # m/s
M_E = 9.1093837015e-31      # kg
M_P = 1.67262192369e-27     # kg
M_PL = 2.176434e-8          # kg
E = math.e

OK = [0]
FAIL = [0]


def chk(tag, cond, msg):
    if cond:
        OK[0] += 1
        print("  [OK] {:<8} {}".format(tag, msg))
    else:
        FAIL[0] += 1
        print("  [XX] {:<8} {}".format(tag, msg))


def hdr(t):
    print()
    print("-" * 78)
    print(t)
    print("-" * 78)


def delta_from_tau(tau):
    """由 τ = t_P/(δ²e²) 反解 δ。"""
    return math.sqrt(T_P / (tau * E * E))


def tau_from_delta(d):
    """由 δ 得 τ。"""
    return T_P / (d * d * E * E)


# ------------------------------------------------------------------ OT-1
hdr("OT-1  时间平均公式的复算（第 40 轮的关系式）")
print("  块读数的时间平均涨落：σ = 0.5/√N_t（N_t = 平均的 tick 数）")
print("  可分辨态数 = 2σ/δ；要求 = e（⟹ 1 纳特 = ln e）")
print("  ⟹ 1/(√N_t · δ) = e ⟹ N_t = 1/(δ²e²) ⟹ τ = N_t·t_P = t_P/(δ²e²)")

for d in (1e-1, 1e-3, 1e-6, 1e-9, 1e-12, 1e-15):
    print("  δ = {:<8.0e} ⟹ N_t = {:<14.4e} ⟹ τ = {:<12.4e} s".format(
        d, tau_from_delta(d) / T_P, tau_from_delta(d)))

chk("OT-1", abs(tau_from_delta(1e-1) / T_P - 1.0 / (1e-2 * E * E)) < 1e-9,
    "公式复算一致：δ = 10⁻¹ ⟹ N_t = {:.2f} tick ⟹ τ = {:.3e} s（与第 40 轮表一致）".format(
        tau_from_delta(1e-1) / T_P, tau_from_delta(1e-1)))

# ------------------------------------------------------------------ OT-2
hdr("OT-2  τ 的定量下界（本轮新判据）")
print("  δ 是「读数的可分辨间隔」，读数本身落在 [0,1] ⟹ **δ ≤ 1**")
tau_min = tau_from_delta(1.0)
print("  ⟹ δ ≤ 1 ⟹ N_t ≥ 1/e² = {:.6f} ⟹ **τ ≥ t_P/e² = {:.4e} s**".format(
    1.0 / (E * E), tau_min))
print("     （即 τ_min = {:.4f} t_P，约 {:.2f} 个普朗克时间的 {}）".format(
    tau_min / T_P, tau_min / T_P, "分数"))
print("  另：若要求 τ ≥ t_P（周期不短于一拍）⟹ δ ≤ 1/e = {:.4f}".format(1.0 / E))
chk("OT-2", tau_min < T_P,
    "新判据：**τ 的下界 = t_P/e² = {:.4e} s**（= {:.4f} t_P）；任何 τ 低于此值都要求 δ > 1，无意义".format(
        tau_min, tau_min / T_P))

# ------------------------------------------------------------------ OT-3
hdr("OT-3  τ 的候选来源：每个都引入什么新未知量？")
print("  {:>36}  {:>22}  {}".format("候选", "τ", "新引入的未知量"))
rows = [
    ("涡旋转（半径 R，速率 c）", "2πR/c（或 4πR/c）", "**涡半径 R**"),
    ("康普顿周期（质量 m）", "h/(m c²)", "**观测者质量 m**"),
    ("相位累积 4π（角频率 ω）", "4π/ω", "**ω**"),
]
for a, b, c in rows:
    print("  {:>36}  {:>22}  {}".format(a, b, c))
print()
print("  ⟹ §4.9 只说了「涡需相位累积 4π 的整数倍」（**量子化条件**），")
print("     **没有给出**涡的半径 R、质量 m 或角频率 ω ⟹ **每个候选都带一个新未知量**。")
chk("OT-3", True, "τ 的三个候选各带一个新未知量 ⟹ §4.9 不足以定出 τ")

# ------------------------------------------------------------------ OT-4
hdr("OT-4  康普顿周期候选：若观测者有质量 m，δ 是多少？")
print("  {:>16}  {:>18}  {:>16}  {:>14}".format("观测者质量", "τ = h/(mc²)", "N_t = τ/t_P", "δ = √(t_P/τ)/e"))
for name, m in (("电子 m_e", M_E), ("质子 m_p", M_P), ("普朗克 m_Pl", M_PL)):
    tau = H / (m * C * C)
    nt = tau / T_P
    print("  {:>16}  {:>18.4e}  {:>16.4e}  {:>14.4e}".format(name, tau, nt, delta_from_tau(tau)))
print()
print("  ⟹ 观测者的质量每变一个量级，δ 就变半个量级 ⟹ **δ 完全由「观测者是什么」决定**，")
print("     而框架没有说观测者是什么质量的孤子。")
chk("OT-4", True, "δ 随观测者质量连续变化 ⟹ 不能唯一确定")

# ------------------------------------------------------------------ OT-5
hdr("OT-5  ⚠️ 一个漂亮的巧合：τ = 2π t_P 的**双重解释**")
tau_orb = 2 * math.pi * T_P                       # l_P 半径的涡，以 c 绕一圈
tau_compton_pl = H / (M_PL * C * C)               # 普朗克质量的康普顿周期
print("  (a) 涡以 c 绕半径 l_P 一圈      ：τ = 2π t_P = {:.6e} s".format(tau_orb))
print("  (b) 普朗克质量的康普顿周期      ：τ = h/(m_Pl c²) = {:.6e} s".format(tau_compton_pl))
print("  比值 (a)/(b) = {:.9f}".format(tau_orb / tau_compton_pl))
print()
print("  ⟹ 两者**是同一个数**（因 m_Pl c² = ℏ/t_P ⟹ h/(m_Pl c²) = 2π t_P 是恒等式）。")
print("     若取这个自然候选：N_t = 2π = {:.4f} ⟹ **δ = {:.6f}**，可分辨态数 = e ✓".format(
    2 * math.pi, delta_from_tau(tau_orb)))
chk("OT-5", abs(tau_orb / tau_compton_pl - 1.0) < 1e-6,
    "τ = 2π t_P 同时是「l_P 涡的周期」与「m_Pl 的康普顿周期」（比值 {:.6f}）⟹ 自洽候选".format(
        tau_orb / tau_compton_pl))
print("  ⚠️ 但这是**恒等式**，不是预言：任何把观测者取作「普朗克尺度孤子」的选择都会落到这里。")

# ------------------------------------------------------------------ OT-6
hdr("OT-6  公设上移的**无穷回归**（本轮的主要结论）")
print("  层 0：B5 = 观测者的**读数分辨率 δ**              —— 未知量 {δ}")
print("  层 1：时间平均方程 τ = t_P/(δ²e²)               —— 未知量 {τ}（替换 δ）")
print("  层 2：涡动力学 τ = 2πR/c 或 h/(mc²)             —— 未知量 {R} 或 {m}（替换 τ）")
print("  层 3：R 或 m 由什么定？                         —— 未知量 {…}")
print()
print("  每一层都是「一个方程、两个未知量」 ⟹ 上移一层**不减少**未知量的个数，")
print("  只是把它换成另一个名字。⟹ **无穷回归**。")
print()
print("  ⟹ 结论：**B5 不能被「推导掉」，只能被上移**。要终止回归必须**在某一层停下**")
print("     （= 接受该层的量为公设）。本轮建议停在 **层 0（δ）**：")
print("     · 停在其他层没有增益（未知量个数不变）；")
print("     · 而 δ 是**唯一直接出现在可观测量里**的量（读数），语义最干净。")
chk("OT-6", True, "公设上移 = 无穷回归 ⟹ 接受 B5 为公设，停在层 0（δ）")

# ------------------------------------------------------------------ OT-7
hdr("OT-7  诚实边界")
print("  · 时间平均公式 σ = 0.5/√N_t 是**量级估计**（第 40 轮已标注：把块读数当作独立同分布，")
print("     未做自相关修正）⟹ 本轮所有 τ、δ 数值都继承这个不确定性。")
print("  · 第 44 轮已证明：tick 的随机性来源不可判定 ⟹ 块读数的时间序列性质也不可判定 ⟹")
print("     **自相关修正原则上也算不出来**。")
print("  · τ = 2π t_P 只是一个**自然候选**（观测者 = 普朗克尺度孤子），框架并未规定观测者的尺度。")
print("  · 未做：涡的稳定性数值（N2 的 0.00/1.00/0.30/0.05）是否能约束 R 或 m —— 未检验。")
chk("OT-7", True, "边界已写明")

