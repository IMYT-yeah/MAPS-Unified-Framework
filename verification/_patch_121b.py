def splice_row(path, anchor_prefix, new_row, guard, tag):
    L = io.open(path, encoding='utf-8').read().split('\n')
    if guard in '\n'.join(L):
        print('  [SKIP] %s 已存在' % tag); return
    idx = [i for i, s in enumerate(L) if s.startswith(anchor_prefix)]
    if len(idx) != 1:
        print('  [XX] %s 锚点行命中 %d 次 —— 拒绝' % (tag, len(idx))); return
    i = idx[0]
    L[i + 1:i + 1] = [new_row]
    io.open(path, 'w', encoding='utf-8').write('\n'.join(L))
    # 管道数一致性自检
    print('  [OK] %s 已插于 L%d 之后（管道数 新 %d / 锚 %d）'
          % (tag, i + 1, new_row.count('|'), L[i].count('|')))

def sub_once(path, old, new, tag):
    t = io.open(path, encoding='utf-8').read()
    n = t.count(old)
    if n != 1:
        print('  [XX] %s 命中 %d 次 —— 拒绝' % (tag, n)); return
    io.open(path, 'w', encoding='utf-8').write(t.replace(old, new, 1))
    print('  [OK] %s 已改' % tag)

